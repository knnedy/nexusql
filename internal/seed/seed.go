// Package seed fills a connected database with fake rows in foreign-key order.
package seed

import (
	"context"
	"fmt"
	mrand "math/rand"
	"slices"
	"strings"

	"github.com/brianvoe/gofakeit/v7"
	"github.com/knnedy/nexusql/internal/db"
)

type Options struct {
	RowsPerTable int
	NullChance   float64 // probability [0,1] a nullable, non-key column gets NULL
}

type Result struct {
	RowsInserted map[string]int    // table -> rows inserted
	Skipped      map[string]int    // table -> rows the database rejected on every try
	Problems     map[string]string // table -> why its last row was rejected
}

// maxAttempts bounds how often a row the database rejects (unique or check
// constraint) is regenerated before it is skipped and reported.
const maxAttempts = 5

// Run inserts fake rows into every table in foreign-key order, in one
// transaction, with values sent as parameters and converted like cell edits.
func Run(ctx context.Context, provider db.Provider, schema *db.Schema, opts Options) (*Result, error) {
	if opts.RowsPerTable <= 0 {
		return nil, fmt.Errorf("rowsPerTable must be positive")
	}
	order, links, err := plan(schema)
	if err != nil {
		return nil, err
	}
	tables := map[string]db.Table{}
	for _, t := range schema.Tables {
		tables[t.Name] = t
	}
	enums := map[string]db.EnumType{}
	for _, e := range schema.Enums {
		enums[e.Name] = e
	}

	tx, err := provider.BeginSeedTx(ctx)
	if err != nil {
		return nil, err
	}
	committed := false
	defer func() {
		if !committed {
			_ = tx.Rollback(ctx)
		}
	}()

	g := generator{links: links, enums: enums, nullChance: opts.NullChance, rows: map[string][]map[string]string{}}
	result := &Result{RowsInserted: map[string]int{}, Skipped: map[string]int{}, Problems: map[string]string{}}
	for _, name := range order {
		for range opts.RowsPerTable {
			row, err := g.insertRow(ctx, tx, tables[name])
			if ctx.Err() != nil {
				return nil, ctx.Err()
			}
			if err != nil {
				result.Skipped[name]++
				result.Problems[name] = err.Error()
				continue
			}
			result.RowsInserted[name]++
			g.rows[name] = append(g.rows[name], row)
		}
	}
	for _, name := range order {
		if err := g.backfill(ctx, tx, tables[name]); err != nil {
			if ctx.Err() != nil {
				return nil, ctx.Err()
			}
			result.Problems[name] = err.Error()
		}
	}

	if err := tx.Commit(ctx); err != nil {
		return nil, fmt.Errorf("failed to commit seed transaction: %w", err)
	}
	committed = true
	return result, nil
}

type generator struct {
	links      map[string][]*link // source table -> its foreign keys
	enums      map[string]db.EnumType
	nullChance float64
	rows       map[string][]map[string]string // table -> non-NULL values of each seeded row
}

// insertRow inserts one row, regenerating it when the database rejects it,
// and returns its non-NULL values, database-assigned keys included.
func (g *generator) insertRow(ctx context.Context, tx db.SeedTx, table db.Table) (map[string]string, error) {
	var auto []db.Field
	for _, f := range table.Fields {
		if f.IsPrimaryKey && f.AutoGenerated {
			auto = append(auto, f)
		}
	}
	var lastErr error
	for range maxAttempts {
		vals, err := g.row(table)
		if err != nil {
			return nil, err // retrying cannot help
		}
		var fields []db.Field
		var values []*string
		for _, f := range table.Fields {
			if v, ok := vals[f.Name]; ok {
				fields, values = append(fields, f), append(values, v)
			}
		}
		got, err := tx.Insert(ctx, table, fields, values, auto)
		if err == nil {
			row := map[string]string{}
			for i, f := range fields {
				if values[i] != nil {
					row[f.Name] = *values[i]
				}
			}
			for i, v := range got {
				row[auto[i].Name] = v
			}
			return row, nil
		}
		lastErr = err
		if ctx.Err() != nil {
			break
		}
	}
	return nil, lastErr
}

// row generates one row as field -> text (nil: NULL); fields it leaves out
// get the database's value. Foreign keys come first, so a key made of them
// takes its parents' values.
func (g *generator) row(table db.Table) (map[string]*string, error) {
	vals := map[string]*string{}
	reserved := map[string]bool{}
	var selfLinks []*link
	for _, l := range g.links[table.Name] {
		if slices.ContainsFunc(l.SourceFields, func(f string) bool { _, ok := vals[f]; return ok || reserved[f] }) {
			continue // overlaps a key already filled
		}
		switch {
		case l.deferred:
			for _, f := range l.SourceFields {
				vals[f] = nil
			}
		case l.self():
			selfLinks = append(selfLinks, l)
			for _, f := range l.SourceFields {
				reserved[f] = true
			}
		default:
			parent := g.pick(l.TargetTable, l.TargetFields, -1)
			if parent == nil && !l.nullable {
				return nil, fmt.Errorf("no rows in %s for %s to reference", l.TargetTable, columns(l))
			}
			fill(vals, l, parent)
		}
	}

	for _, f := range table.Fields {
		if _, ok := vals[f.Name]; ok || reserved[f.Name] || f.AutoGenerated {
			continue
		}
		switch {
		case f.IsPrimaryKey:
			s := generatePKValue(f)
			vals[f.Name] = &s
		case f.Nullable && mrand.Float64() < g.nullChance:
			vals[f.Name] = nil
		default:
			s := GenerateFakeValue(f, g.enums)
			vals[f.Name] = &s
		}
	}

	// A required self-reference points at an earlier row, or else at itself.
	for _, l := range selfLinks {
		parent := g.pick(table.Name, l.TargetFields, -1)
		if parent == nil {
			parent = own(vals, l.TargetFields)
		}
		if parent == nil {
			return nil, fmt.Errorf("%s needs an existing row of %s to reference", columns(l), table.Name)
		}
		fill(vals, l, parent)
	}
	return vals, nil
}

// backfill points the deferred keys of table's seeded rows at parent rows.
func (g *generator) backfill(ctx context.Context, tx db.SeedTx, table db.Table) error {
	var pk []db.Field
	byName := map[string]db.Field{}
	for _, f := range table.Fields {
		byName[f.Name] = f
		if f.IsPrimaryKey {
			pk = append(pk, f)
		}
	}
	for _, l := range g.links[table.Name] {
		if !l.deferred {
			continue
		}
		if len(pk) == 0 {
			return fmt.Errorf("%s left empty: %s has no primary key to update rows by", columns(l), table.Name)
		}
		fields := make([]db.Field, len(l.SourceFields))
		for i, name := range l.SourceFields {
			fields[i] = byName[name]
		}
	rows:
		for i, row := range g.rows[table.Name] {
			skip := -1
			if l.self() {
				skip = i // not itself, when another row exists
			}
			parent := g.pick(l.TargetTable, l.TargetFields, skip)
			if parent == nil {
				continue
			}
			key := make([]db.KeyValue, len(pk))
			for j, f := range pk {
				v, ok := row[f.Name]
				if !ok {
					continue rows
				}
				key[j] = db.KeyValue{Field: f, Value: v}
			}
			vals := map[string]*string{}
			fill(vals, l, parent)
			values := make([]*string, len(fields))
			for j, f := range fields {
				values[j] = vals[f.Name]
			}
			if err := tx.Update(ctx, table, key, fields, values); err != nil {
				return fmt.Errorf("%s left empty: %w", columns(l), err)
			}
		}
	}
	return nil
}

// pick returns a random seeded row of table with every one of fields set,
// other than row skip when another exists; nil when there is none.
func (g *generator) pick(table string, fields []string, skip int) map[string]string {
	var ok []int
	for i, row := range g.rows[table] {
		if !slices.ContainsFunc(fields, func(f string) bool { _, set := row[f]; return !set }) {
			ok = append(ok, i)
		}
	}
	if len(ok) > 1 {
		ok = slices.DeleteFunc(ok, func(i int) bool { return i == skip })
	}
	if len(ok) == 0 {
		return nil
	}
	return g.rows[table][ok[mrand.Intn(len(ok))]]
}

// own returns the row's own values for fields, when it has them all.
func own(vals map[string]*string, fields []string) map[string]string {
	row := map[string]string{}
	for _, f := range fields {
		if v := vals[f]; v != nil {
			row[f] = *v
		} else {
			return nil
		}
	}
	return row
}

// fill sets l's source columns from parent (all NULL when parent is nil).
func fill(vals map[string]*string, l *link, parent map[string]string) {
	for i, f := range l.SourceFields {
		if parent == nil {
			vals[f] = nil
			continue
		}
		v := parent[l.TargetFields[i]]
		vals[f] = &v
	}
}

func columns(l *link) string {
	return l.SourceTable + "." + strings.Join(l.SourceFields, ", ")
}

// generatePKValue returns a client-generated primary key value as text.
func generatePKValue(f db.Field) string {
	switch f.Type {
	case db.FieldTypeUUID, db.FieldTypeText, db.FieldTypeVarchar, db.FieldTypeChar:
		return gofakeit.UUID()
	default:
		// integer-ish PK with no sequence/default behind it
		return fmt.Sprintf("%d", gofakeit.Number(100000, 9999999))
	}
}

// GenerateFakeValue returns a fake value for f as text: an enum member, then a
// value fitting the column name, then one fitting the type.
func GenerateFakeValue(f db.Field, enums map[string]db.EnumType) string {
	if enum, ok := enums[string(f.Type)]; ok && len(enum.Values) > 0 {
		return gofakeit.RandomString(enum.Values)
	}
	if v, ok := generateByColumnName(f); ok {
		return v
	}
	switch f.Type {
	case db.FieldTypeSerial, db.FieldTypeBigserial, db.FieldTypeInteger, db.FieldTypeBigint, db.FieldTypeSmallint:
		return fmt.Sprintf("%d", gofakeit.Number(1, 10000))
	case db.FieldTypeNumeric, db.FieldTypeReal, db.FieldTypeDoublePrecision:
		return fmt.Sprintf("%.2f", gofakeit.Float64Range(0, 999)) // fits NUMERIC(5,2)
	case db.FieldTypeBoolean:
		return fmt.Sprintf("%v", gofakeit.Bool())
	case db.FieldTypeUUID:
		return gofakeit.UUID()
	case db.FieldTypeDate:
		return gofakeit.Date().Format("2006-01-02")
	case db.FieldTypeTime:
		return gofakeit.Date().Format("15:04:05")
	case db.FieldTypeTimestamp:
		return gofakeit.Date().Format("2006-01-02 15:04:05")
	case db.FieldTypeTimestamptz:
		return gofakeit.Date().Format("2006-01-02 15:04:05-07")
	case db.FieldTypeInterval:
		return fmt.Sprintf("%d days", gofakeit.Number(1, 30))
	case db.FieldTypeJSON, db.FieldTypeJSONB:
		return fmt.Sprintf(`{"seed": %d}`, gofakeit.Number(1, 1000))
	case db.FieldTypeBytea:
		return fmt.Sprintf(`\x%x`, gofakeit.LetterN(16))
	case db.FieldTypeChar:
		return gofakeit.Letter()
	case db.FieldTypeText:
		return gofakeit.Sentence(8)
	default: // varchar and anything else string-shaped
		return gofakeit.Word()
	}
}

func generateByColumnName(f db.Field) (string, bool) {
	if !isStringType(f.Type) {
		return "", false
	}
	name := strings.ToLower(f.Name)

	switch {
	case strings.Contains(name, "email"):
		return gofakeit.Email(), true
	case strings.Contains(name, "first_name") || name == "firstname":
		return gofakeit.FirstName(), true
	case strings.Contains(name, "last_name") || name == "lastname":
		return gofakeit.LastName(), true
	case name == "name" || strings.HasSuffix(name, "_name"):
		return gofakeit.Name(), true
	case strings.Contains(name, "username"):
		return gofakeit.Username(), true
	case strings.Contains(name, "phone"):
		return gofakeit.Phone(), true
	case strings.Contains(name, "company"):
		return gofakeit.Company(), true
	case strings.Contains(name, "address") && !strings.Contains(name, "email"):
		return gofakeit.Street(), true
	case strings.Contains(name, "city"):
		return gofakeit.City(), true
	case strings.Contains(name, "state"):
		return gofakeit.State(), true
	case strings.Contains(name, "country"):
		return gofakeit.Country(), true
	case strings.Contains(name, "zip") || strings.Contains(name, "postal"):
		return gofakeit.Zip(), true
	case strings.Contains(name, "url") || strings.Contains(name, "website"):
		return gofakeit.URL(), true
	case strings.Contains(name, "title"):
		return gofakeit.JobTitle(), true
	case strings.Contains(name, "description") || strings.Contains(name, "bio"):
		return gofakeit.Sentence(12), true
	case strings.Contains(name, "slug"):
		return strings.ToLower(gofakeit.Word() + "-" + gofakeit.Word()), true
	case strings.Contains(name, "color"):
		return gofakeit.Color(), true
	case strings.Contains(name, "currency"):
		return gofakeit.CurrencyShort(), true
	case strings.Contains(name, "avatar") || strings.Contains(name, "image") || strings.Contains(name, "photo"):
		return gofakeit.URL(), true
	}
	return "", false
}

func isStringType(t db.FieldType) bool {
	switch t {
	case db.FieldTypeChar, db.FieldTypeVarchar, db.FieldTypeText:
		return true
	default:
		return false
	}
}
