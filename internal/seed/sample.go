package seed

import (
	"fmt"

	"github.com/knnedy/nexusql/internal/db"
)

// Sample is rows made the way a seed makes them, without touching the database.
type Sample struct {
	Rows []map[string]*string `json:"rows"` // column -> value, nil is NULL; key and automatic columns left out
	Refs map[string]string    `json:"refs"` // key column -> the table it points at, picked at insert
	Auto []string             `json:"auto"` // columns the database fills
}

// Generate makes n rows of table without inserting them.
func Generate(schema *db.Schema, table string, n int, nullChance float64) (*Sample, error) {
	t, ok := schema.Table(table)
	if !ok {
		return nil, fmt.Errorf("unknown table %q", table)
	}
	_, links, err := plan(schema)
	if err != nil {
		return nil, err
	}
	enums := map[string]db.EnumType{}
	for _, e := range schema.Enums {
		enums[e.Name] = e
	}
	out := &Sample{Rows: []map[string]*string{}, Refs: map[string]string{}, Auto: []string{}}
	for _, l := range links[table] {
		for _, f := range l.SourceFields {
			out.Refs[f] = l.TargetTable
		}
	}
	for _, f := range t.Fields {
		if f.AutoGenerated {
			out.Auto = append(out.Auto, f.Name)
		}
	}
	// Without links every column gets a value; key columns are then dropped.
	g := generator{links: map[string][]*link{}, enums: enums, nullChance: nullChance, rows: map[string][]map[string]string{}}
	for range n {
		vals, err := g.row(t)
		if err != nil {
			return nil, err
		}
		for f := range out.Refs {
			delete(vals, f)
		}
		out.Rows = append(out.Rows, vals)
	}
	return out, nil
}

// Order is the order Run inserts tables in: each after the tables it references.
func Order(schema *db.Schema) ([]string, error) {
	order, _, err := plan(schema)
	return order, err
}
