package export

import (
	"fmt"
	"strings"

	"github.com/knnedy/nexusql/internal/db"
)

// Prisma renders m as a Prisma 7 schema, keeping database names as
// `prisma db pull` does and mapping any that are not valid identifiers.
func Prisma(m *Model) string {
	var b strings.Builder
	b.WriteString("generator client {\n  provider = \"prisma-client-js\"\n}\n\n")
	fmt.Fprintf(&b, "datasource db {\n  provider = %q\n}\n", m.Dialect.PrismaProvider())

	for _, e := range m.Enums {
		var rows [][]string
		for _, v := range e.Values {
			rows = append(rows, []string{v.Ident, mapAttr(v.Ident, v.Name, "@map")})
		}
		fmt.Fprintf(&b, "\nenum %s {\n%s", e.Ident, align(rows))
		if e.Ident != e.Name {
			fmt.Fprintf(&b, "\n  @@map(%s)\n", prismaString(e.Name))
		}
		b.WriteString("}\n")
	}

	for _, t := range m.Tables {
		var rows [][]string
		var block []string
		ignored := len(t.PK) == 0 && len(t.Unique) == 0
		for _, f := range t.Fields {
			rows = append(rows, prismaField(m, t, f))
		}
		for _, r := range t.Out {
			attr := fmt.Sprintf("@relation(%sfields: [%s], references: [%s]%s)",
				relName(r), idents(r.FromFields), idents(r.ToFields), prismaActions(r))
			rows = append(rows, []string{r.FromIdent, r.To.Ident + optional(r.Optional), attr})
		}
		for _, r := range t.In {
			typ := r.From.Ident + "[]"
			if r.OneToOne {
				typ = r.From.Ident + "?"
			}
			attr := ""
			if r.Name != "" {
				attr = fmt.Sprintf("@relation(%q)", r.Name)
			}
			rows = append(rows, []string{r.ToIdent, typ, attr})
		}
		if len(t.PK) > 1 {
			block = append(block, fmt.Sprintf("@@id([%s])", idents(t.PK)))
		}
		for _, u := range t.Unique {
			if len(u) > 1 {
				block = append(block, fmt.Sprintf("@@unique([%s])", idents(u)))
			}
		}
		for _, ix := range t.Indexes {
			block = append(block, fmt.Sprintf("@@index([%s]%s)", idents(ix.Fields), indexMap(t, ix)))
		}
		if t.Ident != t.Name {
			block = append(block, fmt.Sprintf("@@map(%s)", prismaString(t.Name)))
		}
		if ignored {
			b.WriteString("\n/// The table has no primary key or unique column, so Prisma Client cannot use it.")
			block = append(block, "@@ignore")
		}
		fmt.Fprintf(&b, "\nmodel %s {\n%s", t.Ident, align(rows))
		if len(block) > 0 {
			b.WriteString("\n")
			for _, a := range block {
				b.WriteString("  ")
				b.WriteString(a)
				b.WriteString("\n")
			}
		}
		b.WriteString("}\n")
	}
	return b.String()
}

func prismaField(m *Model, t *Table, f *Field) []string {
	scalar, native := "", ""
	if f.Enum != nil {
		scalar = f.Enum.Ident
	} else {
		scalar, native = m.Dialect.PrismaType(f.Field)
	}
	if scalar == "" {
		scalar = fmt.Sprintf("Unsupported(%s)", prismaString(f.NativeType))
	}

	var attrs []string
	if len(t.PK) == 1 && t.PK[0] == f {
		attrs = append(attrs, "@id")
	}
	for _, u := range t.Unique {
		if len(u) == 1 && u[0] == f {
			attrs = append(attrs, "@unique")
		}
	}
	if d := prismaDefault(m, f, scalar); d != "" {
		attrs = append(attrs, "@default("+d+")")
	}
	if a := mapAttr(f.Ident, f.Name, "@map"); a != "" {
		attrs = append(attrs, a)
	}
	if native != "" {
		attrs = append(attrs, native)
	}
	// Prisma keys are required; SQLite lets non-rowid key columns hold NULL.
	return []string{f.Ident, scalar + optional(f.Nullable && !f.IsPrimaryKey), strings.Join(attrs, " ")}
}

// prismaDefault renders f's default for a field of the given Prisma type;
// anything Prisma cannot express as a value stays a database expression.
func prismaDefault(m *Model, f *Field, scalar string) string {
	if f.AutoGenerated {
		if scalar == "Int" || scalar == "BigInt" {
			return "autoincrement()"
		}
		return ""
	}
	if f.DefaultValue == nil || strings.HasPrefix(scalar, "Unsupported(") {
		return ""
	}
	d := m.Dialect.Default(f.Field)
	generated := fmt.Sprintf("dbgenerated(%s)", prismaString(*f.DefaultValue))
	switch {
	case d.Kind == db.DefaultNone:
		return ""
	case f.Enum != nil && d.Kind == db.DefaultString:
		for _, v := range f.Enum.Values {
			if v.Name == d.Value {
				return v.Ident
			}
		}
	case d.Kind == db.DefaultNow && scalar == "DateTime":
		return "now()"
	case scalar == "Boolean":
		switch d.Value {
		case "true", "1", "t":
			return "true"
		case "false", "0", "f":
			return "false"
		}
	case scalar == "String" && d.Kind == db.DefaultString:
		return prismaString(d.Value)
	case scalar == "Int" || scalar == "BigInt":
		if (d.Kind == db.DefaultNumber || d.Kind == db.DefaultString) && isInteger(d.Value) {
			return d.Value
		}
	case scalar == "Float" || scalar == "Decimal":
		if d.Kind == db.DefaultNumber || d.Kind == db.DefaultString && db.ParseDefault(d.Value).Kind == db.DefaultNumber {
			return d.Value
		}
	}
	return generated
}

func isInteger(s string) bool {
	s = strings.TrimPrefix(s, "-")
	return s != "" && strings.Trim(s, "0123456789") == ""
}

var prismaAction = map[db.RefAction]string{
	db.NoAction: "NoAction", db.Restrict: "Restrict", db.Cascade: "Cascade",
	db.SetNull: "SetNull", db.SetDefault: "SetDefault",
}

// prismaActions states the actions that differ from Prisma's defaults, as
// prisma db pull does. Prisma rejects SetNull on a required relation.
func prismaActions(r *Relation) string {
	var out string
	onDelete := db.Restrict
	if r.Optional {
		onDelete = db.SetNull
	}
	for _, a := range []struct {
		name          string
		got, standard db.RefAction
	}{{"onDelete", r.OnDelete, onDelete}, {"onUpdate", r.OnUpdate, db.Cascade}} {
		if a.got != a.standard && prismaAction[a.got] != "" && (a.got != db.SetNull || r.Optional) {
			out += fmt.Sprintf(", %s: %s", a.name, prismaAction[a.got])
		}
	}
	return out
}

// indexMap names the index unless it has Prisma's default name.
func indexMap(t *Table, ix Index) string {
	names := []string{t.Name}
	for _, f := range ix.Fields {
		names = append(names, f.Name)
	}
	if ix.Name == strings.Join(names, "_")+"_idx" {
		return ""
	}
	return ", map: " + prismaString(ix.Name)
}

func relName(r *Relation) string {
	if r.Name == "" {
		return ""
	}
	return fmt.Sprintf("%q, ", r.Name)
}

func idents(fs []*Field) string {
	names := make([]string, len(fs))
	for i, f := range fs {
		names[i] = f.Ident
	}
	return strings.Join(names, ", ")
}

func optional(nullable bool) string {
	if nullable {
		return "?"
	}
	return ""
}

func mapAttr(ident, name, attr string) string {
	if ident == name {
		return ""
	}
	return fmt.Sprintf("%s(%s)", attr, prismaString(name))
}

// prismaString quotes s as a Prisma string literal.
func prismaString(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// align lays rows out in columns, as prisma format does.
func align(rows [][]string) string {
	widths := map[int]int{}
	for _, r := range rows {
		for i, c := range r[:len(r)-1] {
			widths[i] = max(widths[i], len(c))
		}
	}
	var b strings.Builder
	for _, r := range rows {
		line := "  "
		for i, c := range r {
			if i < len(r)-1 {
				line += c + strings.Repeat(" ", widths[i]-len(c)+1)
			} else {
				line += c
			}
		}
		b.WriteString(strings.TrimRight(line, " "))
		b.WriteString("\n")
	}
	return b.String()
}
