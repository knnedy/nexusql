package export

import (
	"fmt"
	"regexp"
	"strings"
)

var (
	mermaidBare = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_-]*$`)
	// Attribute names allow no spaces or quotes; types allow no spaces.
	mermaidNameChars = regexp.MustCompile(`[^A-Za-z0-9_-]`)
	mermaidTypeChars = regexp.MustCompile(`[^A-Za-z0-9_(),\[\]-]`)
)

// Mermaid renders m as a Mermaid entity-relationship diagram: tables with
// their columns and keys, and one line per foreign key.
func Mermaid(m *Model) string {
	var b strings.Builder
	b.WriteString("erDiagram\n  %% Generated by NexusQL from the introspected schema.\n")
	for _, t := range m.Tables {
		fmt.Fprintf(&b, "\n  %s {\n", mermaidEntity(t.Name))
		for _, f := range t.Fields {
			line := mermaidType(f) + " " + mermaidAttr(f.Name)
			if keys := mermaidKeys(t, f); keys != "" {
				line += " " + keys
			}
			if mermaidAttr(f.Name) != f.Name {
				line += ` "` + mermaidText(f.Name) + `"`
			}
			fmt.Fprintf(&b, "    %s\n", line)
		}
		b.WriteString("  }\n")
	}
	first := true
	for _, t := range m.Tables {
		for _, r := range t.Out {
			if first {
				b.WriteString("\n")
				first = false
			}
			fmt.Fprintf(&b, "  %s %s %s : \"%s\"\n", mermaidEntity(r.To.Name), mermaidCardinality(r), mermaidEntity(t.Name), mermaidText(fieldNames(r.FromFields)))
		}
	}
	return b.String()
}

// mermaidCardinality reads the key: the referenced row is optional when a key
// column is nullable, the referencing side is one row at most when its columns
// are unique, and the link is identifying when they are part of its primary key.
func mermaidCardinality(r *Relation) string {
	left := "||"
	if r.Optional {
		left = "|o"
	}
	right := "o{"
	if r.OneToOne || r.From.hasUnique(r.FromFields) {
		right = "o|"
	}
	line := ".."
	if subset(r.FromFields, r.From.PK) {
		line = "--"
	}
	return left + line + right
}

func mermaidKeys(t *Table, f *Field) string {
	var keys []string
	if f.IsPrimaryKey {
		keys = append(keys, "PK")
	}
	if f.IsForeignKey {
		keys = append(keys, "FK")
	}
	for _, u := range t.DeclaredUnique {
		if len(u) == 1 && u[0] == f {
			keys = append(keys, "UK")
		}
	}
	return strings.Join(keys, ", ")
}

func mermaidType(f *Field) string {
	t := strings.TrimSpace(f.NativeType)
	if f.Enum != nil {
		t = f.Enum.Name
	}
	if t == "" {
		return "any" // SQLite allows a column without a declared type
	}
	return mermaidStart(mermaidTypeChars.ReplaceAllString(t, "_"))
}

func mermaidAttr(name string) string {
	return mermaidStart(mermaidNameChars.ReplaceAllString(name, "_"))
}

// mermaidStart makes s begin with a letter or underscore, as names must.
func mermaidStart(s string) string {
	if s == "" || !(s[0] == '_' || s[0]|0x20 >= 'a' && s[0]|0x20 <= 'z') {
		return "_" + s
	}
	return s
}

func mermaidEntity(name string) string {
	if mermaidBare.MatchString(name) {
		return name
	}
	return `"` + mermaidText(name) + `"`
}

// mermaidText is text inside a Mermaid string, which cannot hold a double quote.
func mermaidText(s string) string { return strings.ReplaceAll(s, `"`, "'") }

func fieldNames(fs []*Field) string {
	names := make([]string, len(fs))
	for i, f := range fs {
		names[i] = f.Name
	}
	return strings.Join(names, ", ")
}

func subset(fs, of []*Field) bool {
	for _, f := range fs {
		found := false
		for _, o := range of {
			found = found || o == f
		}
		if !found {
			return false
		}
	}
	return len(fs) > 0
}
