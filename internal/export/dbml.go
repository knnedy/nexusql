package export

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/knnedy/nexusql/internal/db"
	"github.com/knnedy/nexusql/internal/sqlscan"
)

var (
	dbmlBare = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)
	// A DBML type may be one word with arguments; anything else is quoted.
	dbmlBareType = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*(\(\d+(,\s*\d+)?\))?(\[\])?$`)
	dbmlKeywords = map[string]bool{
		"table": true, "ref": true, "enum": true, "note": true, "indexes": true, "checks": true,
		"project": true, "tablegroup": true, "tablepartial": true, "records": true, "as": true,
	}
)

// DBML renders m as DBML (dbdiagram.io): enums, tables with their column
// settings, indexes and checks, then references.
func DBML(m *Model) string {
	var b strings.Builder
	b.WriteString("// Generated by NexusQL from the introspected schema.\n")
	for _, e := range m.Enums {
		fmt.Fprintf(&b, "\nEnum %s {\n", dbmlName(e.Name))
		for _, v := range e.Values {
			fmt.Fprintf(&b, "  %s\n", dbmlName(v.Name))
		}
		b.WriteString("}\n")
	}
	for _, t := range m.Tables {
		fmt.Fprintf(&b, "\nTable %s {\n", dbmlName(t.Name))
		for _, f := range t.Fields {
			fmt.Fprintf(&b, "  %s %s%s\n", dbmlName(f.Name), dbmlType(f), dbmlSettings(m, t, f))
		}
		var idx []string
		if len(t.PK) > 1 {
			idx = append(idx, dbmlCols(t.PK)+" [pk]")
		}
		for _, u := range t.DeclaredUnique {
			if len(u) > 1 {
				idx = append(idx, dbmlCols(u)+" [unique]")
			}
		}
		for _, ix := range t.Indexes {
			idx = append(idx, fmt.Sprintf("%s [name: %s]", dbmlCols(ix.Fields), dbmlString(ix.Name)))
		}
		if len(idx) > 0 {
			b.WriteString("\n  Indexes {\n")
			for _, s := range idx {
				fmt.Fprintf(&b, "    %s\n", s)
			}
			b.WriteString("  }\n")
		}
		if len(t.Checks) > 0 {
			b.WriteString("\n  Checks {\n")
			for _, c := range t.Checks {
				line := dbmlExpr(c.Expr)
				if c.Name != "" {
					line += " [name: " + dbmlString(c.Name) + "]"
				}
				fmt.Fprintf(&b, "    %s\n", line)
			}
			b.WriteString("  }\n")
		}
		b.WriteString("}\n")
	}
	first := true
	for _, t := range m.Tables {
		for _, r := range t.Out {
			if first {
				b.WriteString("\n")
				first = false
			}
			op := ">"
			if r.OneToOne {
				op = "-"
			}
			fmt.Fprintf(&b, "Ref: %s.%s %s %s.%s%s\n", dbmlName(t.Name), dbmlRefCols(r.FromFields), op,
				dbmlName(r.To.Name), dbmlRefCols(r.ToFields), dbmlActions(r))
		}
	}
	return b.String()
}

func dbmlSettings(m *Model, t *Table, f *Field) string {
	var s []string
	pk := len(t.PK) == 1 && t.PK[0] == f
	if pk {
		s = append(s, "pk")
	}
	if f.AutoGenerated {
		s = append(s, "increment")
	}
	if !f.Nullable && !pk {
		s = append(s, "not null")
	}
	for _, u := range t.DeclaredUnique {
		if len(u) == 1 && u[0] == f {
			s = append(s, "unique")
		}
	}
	if d := dbmlDefault(m, f); d != "" {
		s = append(s, "default: "+d)
	}
	if len(s) == 0 {
		return ""
	}
	return " [" + strings.Join(s, ", ") + "]"
}

func dbmlDefault(m *Model, f *Field) string {
	if f.AutoGenerated || f.DefaultValue == nil {
		return ""
	}
	d := m.Dialect.Default(f.Field)
	switch d.Kind {
	case db.DefaultNone:
		return ""
	case db.DefaultString:
		if numericType(f.Type) && db.ParseDefault(d.Value).Kind == db.DefaultNumber {
			return d.Value // Postgres keeps '-1'::integer as a string literal
		}
		return dbmlString(d.Value)
	case db.DefaultNumber, db.DefaultBool:
		return d.Value
	}
	return dbmlExpr(*f.DefaultValue)
}

func numericType(t db.FieldType) bool {
	switch t {
	case db.FieldTypeSmallint, db.FieldTypeInteger, db.FieldTypeSerial, db.FieldTypeBigint,
		db.FieldTypeBigserial, db.FieldTypeNumeric, db.FieldTypeReal, db.FieldTypeDoublePrecision:
		return true
	}
	return false
}

func dbmlType(f *Field) string {
	if f.Enum != nil {
		return dbmlName(f.Enum.Name)
	}
	t := strings.TrimSpace(f.NativeType)
	switch {
	case t == "":
		return "any" // SQLite allows a column without a declared type
	case dbmlBareType.MatchString(t):
		return t
	}
	return `"` + strings.ReplaceAll(t, `"`, `\"`) + `"`
}

func dbmlActions(r *Relation) string {
	var s []string
	if r.OnDelete != "" && r.OnDelete != db.NoAction {
		s = append(s, "delete: "+strings.ToLower(string(r.OnDelete)))
	}
	if r.OnUpdate != "" && r.OnUpdate != db.NoAction {
		s = append(s, "update: "+strings.ToLower(string(r.OnUpdate)))
	}
	if len(s) == 0 {
		return ""
	}
	return " [" + strings.Join(s, ", ") + "]"
}

func dbmlRefCols(fs []*Field) string {
	if len(fs) == 1 {
		return dbmlName(fs[0].Name)
	}
	return dbmlCols(fs)
}

func dbmlCols(fs []*Field) string {
	names := make([]string, len(fs))
	for i, f := range fs {
		names[i] = dbmlName(f.Name)
	}
	if len(fs) == 1 {
		return names[0]
	}
	return "(" + strings.Join(names, ", ") + ")"
}

func dbmlName(s string) string {
	if dbmlBare.MatchString(s) && !dbmlKeywords[strings.ToLower(s)] {
		return s
	}
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

func dbmlString(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s) + "'"
}

// dbmlExpr writes a SQL expression as a DBML backtick literal, which has no
// escapes: backtick-quoted names (MySQL) become bare or double-quoted names.
func dbmlExpr(s string) string {
	if !strings.Contains(s, "`") {
		return "`" + s + "`"
	}
	var b strings.Builder
	last := 0
	for _, t := range db.Tokenize(s, sqlscan.MySQL) {
		if t.Kind != 'i' || s[t.Pos] != '`' {
			continue
		}
		b.WriteString(s[last:t.Pos])
		if dbmlBare.MatchString(t.Text) {
			b.WriteString(t.Text)
		} else {
			b.WriteString(`"`)
			b.WriteString(strings.ReplaceAll(t.Text, `"`, `""`))
			b.WriteString(`"`)
		}
		last = t.End
	}
	b.WriteString(s[last:])
	return "`" + strings.ReplaceAll(b.String(), "`", "'") + "`"
}
