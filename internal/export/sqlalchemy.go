package export

import (
	"fmt"
	"slices"
	"strings"

	"github.com/knnedy/nexusql/internal/db"
)

// pyReserved are names a declarative class attribute cannot take.
var pyReserved = map[string]bool{"metadata": true, "registry": true}

var pyKeywords = strings.Fields(`False None True and as assert async await break class continue def
	del elif else except finally for from global if import in is lambda nonlocal not or pass raise
	return try while with yield`)

// SQLAlchemy renders m as SQLAlchemy 2.0 declarative models: a mapped class
// per keyed table, a Table for keyless ones, and relationships both ways.
func SQLAlchemy(m *Model) string {
	s := &saWriter{m: m, classes: map[*Table]string{}, enums: map[*Enum]string{}, attrs: map[*Field]string{},
		sa: map[string]bool{}, py: map[string]bool{}, dialect: map[string]bool{}}
	s.name()
	var body strings.Builder
	for _, e := range m.Enums {
		vals := make([]string, len(e.Values))
		for i, v := range e.Values {
			vals[i] = pyString(v.Name)
		}
		s.sa["Enum"] = true
		fmt.Fprintf(&body, "\n\n%s = Enum(%s, name=%s)\n", s.enums[e], strings.Join(vals, ", "), pyString(e.Name))
	}
	for _, t := range m.Tables {
		if len(t.PK) == 0 {
			s.table(&body, t)
		} else {
			s.class(&body, t)
		}
	}
	return s.head() + body.String()
}

type saWriter struct {
	m       *Model
	classes map[*Table]string
	enums   map[*Enum]string
	attrs   map[*Field]string
	sa      map[string]bool // names imported from sqlalchemy
	py      map[string]bool // stdlib imports: datetime, decimal, uuid, Any, Optional
	dialect map[string]bool // sqlalchemy.dialects modules
	raw     bool
}

func (s *saWriter) name() {
	used := map[string]bool{"Base": true, "Raw": true, "Enum": true, "Table": true, "Column": true, "Mapped": true}
	for _, e := range s.m.Enums {
		s.enums[e] = unique(goName(e.Ident)+"Enum", used)
	}
	for _, t := range s.m.Tables {
		s.classes[t] = unique(goName(t.Ident), used)
		for _, f := range t.Fields {
			a := f.Ident
			if pyReserved[a] || slices.Contains(pyKeywords, a) {
				a += "_"
			}
			s.attrs[f] = a
		}
	}
}

func (s *saWriter) head() string {
	var b strings.Builder
	b.WriteString("# Generated by NexusQL from the introspected schema.\nfrom __future__ import annotations\n")
	var std []string
	for _, m := range []string{"datetime", "decimal", "uuid"} {
		if s.py[m] {
			std = append(std, "import "+m)
		}
	}
	var typing []string
	for _, n := range []string{"Any", "Optional"} {
		if s.py[n] || n == "Any" && s.raw {
			typing = append(typing, n)
		}
	}
	if len(typing) > 0 {
		std = append(std, "from typing import "+strings.Join(typing, ", "))
	}
	if len(std) > 0 {
		b.WriteString("\n")
		b.WriteString(strings.Join(std, "\n"))
		b.WriteString("\n")
	}
	b.WriteString("\n")
	names := make([]string, 0, len(s.sa))
	for n := range s.sa {
		names = append(names, n)
	}
	slices.SortFunc(names, func(a, b string) int {
		if c := strings.Compare(strings.ToLower(a), strings.ToLower(b)); c != 0 {
			return c
		}
		return strings.Compare(a, b)
	})
	fmt.Fprintf(&b, "from sqlalchemy import %s\n", pyWrap("from sqlalchemy import ", names))
	if len(s.dialect) > 0 {
		var ds []string
		for d := range s.dialect {
			ds = append(ds, d)
		}
		slices.Sort(ds)
		fmt.Fprintf(&b, "from sqlalchemy.dialects import %s\n", strings.Join(ds, ", "))
	}
	b.WriteString("from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship\n")
	if s.raw {
		b.WriteString("from sqlalchemy.types import UserDefinedType\n")
	}
	b.WriteString("\n\nclass Base(DeclarativeBase):\n    pass\n")
	if s.raw {
		b.WriteString(`

class Raw(UserDefinedType):
    """A column type written exactly as the database declares it."""

    cache_ok = True

    def __init__(self, ddl: str) -> None:
        self.ddl = ddl

    def get_col_spec(self, **kw: Any) -> str:
        return self.ddl
`)
	}
	return b.String()
}

// pyWrap joins names, in parentheses over several lines when long.
func pyWrap(prefix string, names []string) string {
	line := strings.Join(names, ", ")
	if len(prefix)+len(line) <= 88 {
		return line
	}
	return "(\n    " + strings.Join(names, ",\n    ") + ",\n)"
}

func (s *saWriter) colType(f *Field) string {
	if f.Enum != nil {
		return s.enums[f.Enum]
	}
	t := s.m.Dialect.SQLAlchemy(f.Field).Type
	if t == "" {
		s.raw = true
		return "Raw(" + pyString(strings.TrimSpace(f.NativeType)) + ")"
	}
	// Record what the expression names: dialect modules or sqlalchemy types.
	if mod, _, ok := strings.Cut(t, "."); ok && !strings.Contains(mod, "(") {
		s.dialect[mod] = true
	} else {
		name, _, _ := strings.Cut(t, "(")
		s.sa[name] = true
	}
	return t
}

func (s *saWriter) pyType(f *Field) string {
	if f.Enum != nil {
		return "str"
	}
	if s.m.Dialect.SQLAlchemy(f.Field).Type == "" {
		s.py["Any"] = true
		return "Any"
	}
	switch f.Type {
	case db.FieldTypeSmallint, db.FieldTypeInteger, db.FieldTypeSerial, db.FieldTypeBigint, db.FieldTypeBigserial:
		return "int"
	case db.FieldTypeReal, db.FieldTypeDoublePrecision:
		return "float"
	case db.FieldTypeNumeric:
		s.py["decimal"] = true
		return "decimal.Decimal"
	case db.FieldTypeBoolean:
		return "bool"
	case db.FieldTypeDate:
		s.py["datetime"] = true
		return "datetime.date"
	case db.FieldTypeTimestamp, db.FieldTypeTimestamptz:
		s.py["datetime"] = true
		return "datetime.datetime"
	case db.FieldTypeTime:
		s.py["datetime"] = true
		return "datetime.time"
	case db.FieldTypeInterval:
		s.py["datetime"] = true
		return "datetime.timedelta"
	case db.FieldTypeUUID:
		s.py["uuid"] = true
		return "uuid.UUID"
	case db.FieldTypeBytea:
		return "bytes"
	case db.FieldTypeJSON, db.FieldTypeJSONB:
		s.py["Any"] = true
		return "Any"
	}
	return "str"
}

// columnArgs are the arguments after the type shared by mapped_column and Column.
func (s *saWriter) columnArgs(t *Table, f *Field, core bool) []string {
	var args []string
	switch f.Identity {
	case db.IdentityAlways:
		s.sa["Identity"] = true
		args = append(args, "Identity(always=True)")
	case db.IdentityByDefault:
		s.sa["Identity"] = true
		args = append(args, "Identity()")
	}
	pk := slices.Contains(t.PK, f)
	if pk {
		args = append(args, "primary_key=True")
		if len(t.PK) == 1 && !f.AutoGenerated {
			args = append(args, "autoincrement=False")
		}
	}
	if core || pk {
		args = append(args, fmt.Sprintf("nullable=%s", pyBool(f.Nullable)))
	}
	for _, u := range t.DeclaredUnique {
		if len(u) == 1 && u[0] == f {
			args = append(args, "unique=True")
		}
	}
	switch c := s.m.Dialect.SQLAlchemy(f.Field); {
	case f.DefaultValue == nil || f.AutoGenerated:
	case c.Literal != "":
		args = append(args, "server_default="+pyString(c.Literal))
	default:
		s.sa["text"] = true
		args = append(args, "server_default=text("+pyString(escapeBinds(*f.DefaultValue))+")")
	}
	return args
}

func (s *saWriter) tableArgs(t *Table) []string {
	var out []string
	for _, u := range t.DeclaredUnique {
		if len(u) > 1 {
			s.sa["UniqueConstraint"] = true
			out = append(out, "UniqueConstraint("+pyNames(u)+")")
		}
	}
	for _, r := range t.Out {
		s.sa["ForeignKeyConstraint"] = true
		to := make([]string, len(r.ToFields))
		for i, f := range r.ToFields {
			to[i] = pyString(r.To.Name + "." + f.Name)
		}
		fk := fmt.Sprintf("ForeignKeyConstraint([%s], [%s]", pyNames(r.FromFields), strings.Join(to, ", "))
		if r.ConstraintName != "" && !s.m.Dialect.SQL().InlineForeignKeys {
			fk += ", name=" + pyString(r.ConstraintName)
		}
		if r.OnDelete != "" && r.OnDelete != db.NoAction {
			fk += ", ondelete=" + pyString(string(r.OnDelete))
		}
		if r.OnUpdate != "" && r.OnUpdate != db.NoAction {
			fk += ", onupdate=" + pyString(string(r.OnUpdate))
		}
		out = append(out, fk+")")
	}
	for _, ix := range t.Indexes {
		s.sa["Index"] = true
		out = append(out, "Index("+pyString(ix.Name)+", "+pyNames(ix.Fields)+")")
	}
	for _, c := range t.Checks {
		s.sa["CheckConstraint"] = true
		s.sa["text"] = true
		ck := "CheckConstraint(text(" + pyString(escapeBinds(c.Expr)) + ")"
		if c.Name != "" {
			ck += ", name=" + pyString(c.Name)
		}
		out = append(out, ck+")")
	}
	return out
}

func (s *saWriter) table(b *strings.Builder, t *Table) {
	s.sa["Table"], s.sa["Column"] = true, true
	fmt.Fprintf(b, "\n\n%s = Table(\n    %s,\n    Base.metadata,\n", s.classes[t], pyString(t.Name))
	for _, f := range t.Fields {
		args := append([]string{pyString(f.Name), s.colType(f)}, s.columnArgs(t, f, true)...)
		fmt.Fprintf(b, "    Column(%s),\n", strings.Join(args, ", "))
	}
	for _, a := range s.tableArgs(t) {
		fmt.Fprintf(b, "    %s,\n", a)
	}
	b.WriteString(")\n")
}

func (s *saWriter) class(b *strings.Builder, t *Table) {
	fmt.Fprintf(b, "\n\nclass %s(Base):\n    __tablename__ = %s\n", s.classes[t], pyString(t.Name))
	args := s.tableArgs(t)
	if t.PK[0].Monotonic {
		args = append(args, "{'sqlite_autoincrement': True}")
	}
	if len(args) > 0 {
		b.WriteString("    __table_args__ = (\n")
		for _, a := range args {
			fmt.Fprintf(b, "        %s,\n", a)
		}
		b.WriteString("    )\n")
	}
	b.WriteString("\n")
	for _, f := range t.Fields {
		py := s.pyType(f)
		if f.Nullable {
			s.py["Optional"] = true
			py = "Optional[" + py + "]"
		}
		args := []string{s.colType(f)}
		if s.attrs[f] != f.Name {
			args = append([]string{pyString(f.Name)}, args...)
		}
		args = append(args, s.columnArgs(t, f, false)...)
		fmt.Fprintf(b, "    %s: Mapped[%s] = mapped_column(%s)\n", s.attrs[f], py, strings.Join(args, ", "))
	}
	for _, r := range t.Out {
		if len(r.To.PK) == 0 {
			continue
		}
		typ := s.classes[r.To]
		if r.Optional {
			s.py["Optional"] = true
			typ = "Optional[" + typ + "]"
		}
		opts := []string{pyString(s.classes[r.To]), "foreign_keys=[" + s.attrList(r.FromFields) + "]"}
		if r.From == r.To {
			opts = append(opts, "remote_side=["+s.attrList(r.ToFields)+"]")
		}
		opts = append(opts, "back_populates="+pyString(r.ToIdent))
		fmt.Fprintf(b, "    %s: Mapped[%s] = relationship(%s)\n", r.FromIdent, typ, strings.Join(opts, ", "))
	}
	for _, r := range t.In {
		if len(r.From.PK) == 0 {
			continue
		}
		fks := "[" + s.attrList(r.FromFields) + "]"
		if r.From != r.To {
			parts := make([]string, len(r.FromFields))
			for i, f := range r.FromFields {
				parts[i] = s.classes[r.From] + "." + s.attrs[f]
			}
			fks = pyString("[" + strings.Join(parts, ", ") + "]")
		}
		typ := "list[" + s.classes[r.From] + "]"
		opts := []string{pyString(s.classes[r.From]), "foreign_keys=" + fks, "back_populates=" + pyString(r.FromIdent)}
		if r.OneToOne {
			s.py["Optional"] = true
			typ = "Optional[" + s.classes[r.From] + "]"
			opts = append(opts, "uselist=False")
		}
		fmt.Fprintf(b, "    %s: Mapped[%s] = relationship(%s)\n", r.ToIdent, typ, strings.Join(opts, ", "))
	}
}

func (s *saWriter) attrList(fs []*Field) string {
	names := make([]string, len(fs))
	for i, f := range fs {
		names[i] = s.attrs[f]
	}
	return strings.Join(names, ", ")
}

func pyNames(fs []*Field) string {
	names := make([]string, len(fs))
	for i, f := range fs {
		names[i] = pyString(f.Name)
	}
	return strings.Join(names, ", ")
}

func pyBool(b bool) string {
	if b {
		return "True"
	}
	return "False"
}

// pyString quotes s as a single-quoted Python string literal.
func pyString(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, "'", `\'`, "\n", `\n`, "\r", `\r`).Replace(s) + "'"
}

// escapeBinds backslashes each colon text() would read as a :name parameter.
func escapeBinds(sql string) string {
	var b strings.Builder
	for i := 0; i < len(sql); i++ {
		c := sql[i]
		if c == ':' {
			prev := byte(0)
			if i > 0 {
				prev = sql[i-1]
			}
			next := byte(0)
			if i+1 < len(sql) {
				next = sql[i+1]
			}
			if prev != ':' && prev != '\\' && !isWord(prev) && isWord(next) {
				b.WriteByte('\\')
			}
		}
		b.WriteByte(c)
	}
	return b.String()
}

func isWord(c byte) bool {
	return c == '_' || c >= '0' && c <= '9' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z'
}
