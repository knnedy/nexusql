// gormCheckName is a CHECK name GORM keeps; it reads any other as expression text.
var gormCheckName = regexp.MustCompile(`^[\w-]+$`)

// GORM renders m as GORM models, one struct per table with column tags, its
// foreign keys as belongs-to fields and the other side as has-many slices.
func GORM(m *Model) string {
	g := &gormWriter{m: m, structs: map[*Table]string{}, enums: map[*Enum]string{}, fields: map[*Field]string{}}
	g.name()
	var body strings.Builder
	for _, e := range m.Enums {
		fmt.Fprintf(&body, "\ntype %s string\n\nconst (\n", g.enums[e])
		for _, v := range e.Values {
			fmt.Fprintf(&body, "\t%s %s = %q\n", g.enums[e]+goName(v.Ident), g.enums[e], v.Name)
		}
		body.WriteString(")\n")
	}
	for _, t := range m.Tables {
		g.table(&body, t)
	}
	body.WriteString("\n// Models lists every model, referenced tables first, for\n// db.AutoMigrate(models.Models()...).\nfunc Models() []any {\n\treturn []any{\n")
	for _, t := range parentsFirst(m.Tables) {
		fmt.Fprintf(&body, "\t\t&%s{},\n", g.structs[t])
	}
	body.WriteString("\t}\n}\n")

	var head strings.Builder
	head.WriteString("// Code generated by NexusQL from the introspected schema.\n")
	if m.Dialect.SQL().EnumTypes && len(m.Enums) > 0 {
		head.WriteString("//\n// AutoMigrate does not create enum types; create them once first:\n")
		w := &sqlWriter{m: m, d: m.Dialect.SQL()}
		for _, e := range m.Enums {
			for _, line := range strings.Split(w.enum(e), "\n") {
				head.WriteString("//\t")
				head.WriteString(line)
				head.WriteString("\n")
			}
		}
	}
	head.WriteString("\npackage models\n")
	if g.usesTime {
		head.WriteString("\nimport \"time\"\n")
	}
	src := head.String() + body.String()
	if out, err := format.Source([]byte(src)); err == nil {
		return string(out)
	}
	return src // unformatted rather than nothing; the export check compiles it
}

type gormWriter struct {
	m        *Model
	structs  map[*Table]string
	enums    map[*Enum]string
	fields   map[*Field]string
	rels     map[*Relation][2]string // field names on From and To
	usesTime bool
}

func (g *gormWriter) name() {
	used := map[string]bool{"Models": true}
	for _, e := range g.m.Enums {
		g.enums[e] = unique(goName(e.Ident), used)
	}
	for _, t := range g.m.Tables {
		g.structs[t] = unique(goName(t.Ident), used)
	}
	g.rels = map[*Relation][2]string{}
	for _, t := range g.m.Tables {
		inStruct := map[string]bool{"TableName": true}
		for _, f := range t.Fields {
			g.fields[f] = unique(goName(f.Ident), inStruct)
		}
		for _, r := range t.Out {
			n := g.rels[r]
			n[0] = unique(goName(r.FromIdent), inStruct)
			g.rels[r] = n
		}
	}
	for _, t := range g.m.Tables {
		inStruct := map[string]bool{"TableName": true}
		for _, f := range t.Fields {
			inStruct[g.fields[f]] = true
		}
		for _, r := range t.Out {
			inStruct[g.rels[r][0]] = true
		}
		for _, r := range t.In {
			n := g.rels[r]
			n[1] = unique(goName(r.ToIdent), inStruct)
			g.rels[r] = n
		}
	}
}

func (g *gormWriter) table(b *strings.Builder, t *Table) {
	fmt.Fprintf(b, "\ntype %s struct {\n", g.structs[t])
	for _, f := range t.Fields {
		fmt.Fprintf(b, "\t%s %s %s\n", g.fields[f], g.goType(f), gormTag(g.tag(t, f)))
	}
	for _, r := range t.Out {
		if g.ambiguous(r) {
			fmt.Fprintf(b, "\t// %s is reached from %s: GORM would read a field here as has-one.\n", g.structs[r.To], g.structs[r.To]+"."+g.rels[r][1])
			continue
		}
		fmt.Fprintf(b, "\t%s *%s %s\n", g.rels[r][0], g.structs[r.To], gormTag(g.relTag(r)))
	}
	for _, r := range t.In {
		fmt.Fprintf(b, "\t%s []%s %s\n", g.rels[r][1], g.structs[r.From], gormTag(g.relTag(r)))
	}
	fmt.Fprintf(b, "}\n\nfunc (%s) TableName() string { return %q }\n", g.structs[t], t.Name)
}

// ambiguous reports whether To has fields named like r's key fields: GORM
// tries has-one before belongs-to and would point the key the wrong way.
func (g *gormWriter) ambiguous(r *Relation) bool {
	if r.From == r.To {
		return false // self-references are tried as belongs-to first
	}
	for _, f := range r.FromFields {
		if !slices.ContainsFunc(r.To.Fields, func(x *Field) bool { return g.fields[x] == g.fields[f] }) {
			return false
		}
	}
	return true
}

func (g *gormWriter) relTag(r *Relation) string {
	from := make([]string, len(r.FromFields))
	to := make([]string, len(r.ToFields))
	for i := range r.FromFields {
		from[i], to[i] = g.fields[r.FromFields[i]], g.fields[r.ToFields[i]]
	}
	tag := "foreignKey:" + strings.Join(from, ",") + ";references:" + strings.Join(to, ",")
	var c []string
	if r.OnDelete != "" && r.OnDelete != db.NoAction {
		c = append(c, "OnDelete:"+string(r.OnDelete))
	}
	if r.OnUpdate != "" && r.OnUpdate != db.NoAction {
		c = append(c, "OnUpdate:"+string(r.OnUpdate))
	}
	if len(c) > 0 {
		tag += ";constraint:" + strings.Join(c, ",")
	}
	return tag
}

// gormDataTypes are type names GORM swaps for its own generic types; a
// trailing space keeps the native one.
var gormDataTypes = []string{"bool", "int", "uint", "float", "string", "time", "bytes"}

func (g *gormWriter) tag(t *Table, f *Field) string {
	col := g.m.Dialect.GORM(f.Field)
	typ := strings.TrimSpace(f.NativeType)
	if col.Type != "" {
		typ = col.Type
	}
	if slices.Contains(gormDataTypes, strings.ToLower(typ)) {
		typ += " "
	}
	parts := []string{"column:" + f.Name, "type:" + gormEscape(typ)}
	if slices.Contains(t.PK, f) {
		parts = append(parts, "primaryKey")
	}
	if f.AutoGenerated {
		parts = append(parts, "autoIncrement")
	} else if len(t.PK) > 0 && slices.Contains(t.PK, f) {
		parts = append(parts, "autoIncrement:false")
	}
	if !f.Nullable {
		parts = append(parts, "not null")
	}
	if col.Default != "" {
		parts = append(parts, "default:"+gormEscape(col.Default))
	}
	for _, s := range col.Settings {
		parts = append(parts, gormEscape(s))
	}
	for _, u := range t.DeclaredUnique {
		switch {
		case len(u) == 1 && u[0] == f:
			parts = append(parts, "unique")
		case slices.Contains(u, f):
			parts = append(parts, fmt.Sprintf("uniqueIndex:%s,priority:%d", gormEscape(t.Name+"_"+fieldList(u)+"_key"), slices.Index(u, f)+1))
		}
	}
	for _, ix := range t.Indexes {
		if i := slices.Index(ix.Fields, f); i >= 0 {
			parts = append(parts, fmt.Sprintf("index:%s,priority:%d", gormEscape(ix.Name), i+1))
		}
	}
	// GORM keeps one check per field, so check i rides on field i.
	if i := slices.Index(t.Fields, f); i < len(t.Checks) {
		c := t.Checks[i]
		expr := c.Expr
		if c.Name != "" && gormCheckName.MatchString(c.Name) {
			expr = c.Name + "," + expr
		}
		parts = append(parts, "check:"+gormEscape(expr))
	}
	return strings.Join(parts, ";")
}

func (g *gormWriter) goType(f *Field) string {
	var t string
	unsigned := strings.Contains(strings.ToLower(f.NativeType), "unsigned")
	switch {
	case f.Enum != nil:
		t = g.enums[f.Enum]
	case f.Type == db.FieldTypeSmallint:
		t = "int16"
	case f.Type == db.FieldTypeInteger || f.Type == db.FieldTypeSerial:
		t = "int32"
	case f.Type == db.FieldTypeBigint || f.Type == db.FieldTypeBigserial:
		t = "int64"
	case f.Type == db.FieldTypeReal:
		t = "float32"
	case f.Type == db.FieldTypeDoublePrecision:
		t = "float64"
	case f.Type == db.FieldTypeBoolean:
		t = "bool"
	case f.Type == db.FieldTypeDate || f.Type == db.FieldTypeTimestamp || f.Type == db.FieldTypeTimestamptz:
		t = "time.Time"
		g.usesTime = true
	case f.Type == db.FieldTypeBytea:
		t = "[]byte"
	default:
		t = "string" // text, numeric (exact), uuid, json, time, interval
	}
	if unsigned && strings.HasPrefix(t, "int") {
		t = "u" + t
	}
	if f.Nullable && t != "[]byte" {
		t = "*" + t
	}
	return t
}

// parentsFirst orders tables so each comes after the tables it references
// (depth first, in name order); a cycle keeps the order it was met in.
func parentsFirst(ts []*Table) []*Table {
	var out []*Table
	state := map[*Table]int{} // 1 visiting, 2 done
	var visit func(t *Table)
	visit = func(t *Table) {
		if state[t] != 0 {
			return
		}
		state[t] = 1
		for _, r := range t.Out {
			visit(r.To)
		}
		state[t] = 2
		out = append(out, t)
	}
	for _, t := range ts {
		visit(t)
	}
	return out
}

// goName turns an identifier like author_id into AuthorID.
func goName(ident string) string {
	var b strings.Builder
	for _, part := range strings.Split(ident, "_") {
		switch {
		case part == "":
		case strings.EqualFold(part, "id"):
			b.WriteString("ID")
		default:
			b.WriteString(strings.ToUpper(part[:1]))
			b.WriteString(part[1:])
		}
	}
	if b.Len() == 0 || b.String()[0] >= '0' && b.String()[0] <= '9' {
		return "T" + b.String()
	}
	return b.String()
}

// gormEscape escapes s for gorm (\; separates settings), then for the quoted
// struct tag value.
func gormEscape(s string) string {
	s = strings.ReplaceAll(s, ";", `\;`)
	return strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s)
}

// gormTag is the struct tag literal: raw, or interpreted when it holds a backtick.
func gormTag(settings string) string {
	tag := `gorm:"` + settings + `"`
	if strings.Contains(tag, "`") {
		return strconv.Quote(tag)
	}
	return "`" + tag + "`"
}

func fieldList(fs []*Field) string {
	names := make([]string, len(fs))
	for i, f := range fs {
		names[i] = f.Name
	}
	return strings.Join(names, "_")
}
