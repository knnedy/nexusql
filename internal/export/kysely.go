package export

import (
	"fmt"
	"slices"
	"strings"

	"github.com/knnedy/nexusql/internal/db"
)

// kyselyHelpers are the column types whose select and insert values differ,
// named as kysely-codegen names them. Dialects pick one by name.
var kyselyHelpers = []struct{ name, def string }{
	{"Int8", "ColumnType<string, bigint | number | string, bigint | number | string>"},
	{"Numeric", "ColumnType<string, number | string, number | string>"},
	{"Timestamp", "ColumnType<Date, Date | string, Date | string>"},
	{"Json", "ColumnType<JsonValue, string, string>"},
}

const kyselyJSON = `export type JsonArray = JsonValue[];
export type JsonObject = { [x: string]: JsonValue | undefined };
export type JsonPrimitive = boolean | number | string | null;
export type JsonValue = JsonArray | JsonObject | JsonPrimitive;
`

// Kysely renders m as the Database interface Kysely is typed with: one
// interface per table and a DB interface naming them, as kysely-codegen does.
func Kysely(m *Model) string {
	used := map[string]bool{"DB": true, "JsonArray": true, "JsonObject": true, "JsonPrimitive": true, "JsonValue": true}
	for _, h := range kyselyHelpers {
		used[h.name] = true
	}
	enums := map[*Enum]string{}
	for _, e := range m.Enums {
		enums[e] = unique(pascal(e.Ident), used)
	}
	names := map[*Table]string{}
	for _, t := range m.Tables {
		names[t] = unique(pascal(t.Ident), used)
	}

	imports := map[string]bool{}
	helpers := map[string]bool{}
	var body strings.Builder
	for _, e := range m.Enums {
		vals := make([]string, len(e.Values))
		for i, v := range e.Values {
			vals[i] = db.JSString(v.Name)
		}
		fmt.Fprintf(&body, "\nexport type %s = %s;\n", enums[e], strings.Join(vals, " | "))
	}
	for _, t := range m.Tables {
		fmt.Fprintf(&body, "\nexport interface %s {\n", names[t])
		for _, f := range t.Fields {
			typ := "unknown"
			if f.Enum != nil {
				typ = enums[f.Enum]
			} else if k := m.Dialect.KyselyType(f.Field); k != "" {
				typ = k
			}
			if slices.ContainsFunc(kyselyHelpers, func(h struct{ name, def string }) bool { return h.name == typ }) {
				helpers[typ] = true
			}
			if f.Nullable && typ != "unknown" {
				typ += " | null"
			}
			switch {
			case f.Identity == db.IdentityAlways:
				imports["GeneratedAlways"] = true
				typ = "GeneratedAlways<" + typ + ">"
			case f.AutoGenerated || f.DefaultValue != nil:
				imports["Generated"] = true
				typ = "Generated<" + typ + ">"
			}
			fmt.Fprintf(&body, "  %s: %s;\n", jsKey(f.Name), typ)
		}
		body.WriteString("}\n")
	}
	body.WriteString("\nexport interface DB {\n")
	for _, t := range m.Tables {
		fmt.Fprintf(&body, "  %s: %s;\n", jsKey(t.Name), names[t])
	}
	body.WriteString("}\n")

	var head strings.Builder
	if len(helpers) > 0 {
		imports["ColumnType"] = true
	}
	if len(imports) > 0 {
		list := make([]string, 0, len(imports))
		for name := range imports {
			list = append(list, name)
		}
		slices.Sort(list)
		fmt.Fprintf(&head, "import type { %s } from 'kysely';\n", strings.Join(list, ", "))
	}
	for _, h := range kyselyHelpers {
		if helpers[h.name] {
			fmt.Fprintf(&head, "\nexport type %s = %s;\n", h.name, h.def)
		}
	}
	if helpers["Json"] {
		head.WriteString("\n" + kyselyJSON)
	}
	return head.String() + body.String()
}

// jsKey is name as an object key, quoted unless it is an identifier.
func jsKey(name string) string {
	if dbmlBare.MatchString(name) {
		return name
	}
	return db.JSString(name)
}

// pascal turns an identifier like order_items into OrderItems.
func pascal(ident string) string {
	var b strings.Builder
	for _, part := range strings.Split(ident, "_") {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	if b.Len() == 0 || b.String()[0] >= '0' && b.String()[0] <= '9' {
		return "T" + b.String()
	}
	return b.String()
}
