package export

import (
	"fmt"
	"strings"

	"github.com/knnedy/nexusql/internal/db"
)

// SQL renders m as a DDL script for its own dialect: enum types, tables with
// keys, unique sets and checks, indexes, then foreign keys.
func SQL(m *Model) string {
	d := m.Dialect.SQL()
	q := func(name string) string {
		s := string(d.Quote)
		return s + strings.ReplaceAll(name, s, s+s) + s
	}
	cols := func(fs []*Field) string {
		names := make([]string, len(fs))
		for i, f := range fs {
			names[i] = q(f.Name)
		}
		return strings.Join(names, ", ")
	}
	fk := func(r *Relation) string {
		s := fmt.Sprintf("FOREIGN KEY (%s) REFERENCES %s (%s)", cols(r.FromFields), q(r.To.Name), cols(r.ToFields))
		if r.OnDelete != "" && r.OnDelete != db.NoAction {
			s += " ON DELETE " + string(r.OnDelete)
		}
		if r.OnUpdate != "" && r.OnUpdate != db.NoAction {
			s += " ON UPDATE " + string(r.OnUpdate)
		}
		return s
	}

	var b strings.Builder
	b.WriteString("-- Generated by NexusQL from the introspected schema.\n")
	for _, e := range m.Enums {
		if !d.EnumTypes {
			continue
		}
		vals := make([]string, len(e.Values))
		for i, v := range e.Values {
			vals[i] = sqlString(v.Name)
		}
		fmt.Fprintf(&b, "\nCREATE TYPE %s AS ENUM (%s);\n", q(e.Name), strings.Join(vals, ", "))
	}

	for _, t := range m.Tables {
		var lines []string
		for _, f := range t.Fields {
			typ, keepDefault := m.Dialect.SQLColumnType(f.Field)
			col := strings.TrimSpace(q(f.Name) + " " + typ)
			single := len(t.PK) == 1 && t.PK[0] == f
			if !f.Nullable && !(f.IsPrimaryKey && (d.PKNotNull || f.AutoGenerated)) {
				col += " NOT NULL"
			}
			if keepDefault && f.DefaultValue != nil {
				col += " DEFAULT " + *f.DefaultValue
			}
			if single {
				col += " PRIMARY KEY"
				if f.Monotonic {
					col += " AUTOINCREMENT"
				}
			}
			lines = append(lines, col)
		}
		if len(t.PK) > 1 {
			lines = append(lines, "PRIMARY KEY ("+cols(t.PK)+")")
		}
		for _, u := range t.DeclaredUnique {
			lines = append(lines, "UNIQUE ("+cols(u)+")")
		}
		for _, c := range t.Checks {
			check := "CHECK (" + c.Expr + ")"
			if c.Name != "" {
				check = "CONSTRAINT " + q(c.Name) + " " + check
			}
			lines = append(lines, check)
		}
		if d.InlineForeignKeys {
			for _, r := range t.Out {
				lines = append(lines, fk(r))
			}
		}
		fmt.Fprintf(&b, "\nCREATE TABLE %s (\n  %s\n);\n", q(t.Name), strings.Join(lines, ",\n  "))
	}

	for _, t := range m.Tables {
		for _, ix := range t.Indexes {
			fmt.Fprintf(&b, "\nCREATE INDEX %s ON %s (%s);", q(ix.Name), q(t.Name), cols(ix.Fields))
		}
	}
	if !d.InlineForeignKeys {
		for _, t := range m.Tables {
			for _, r := range t.Out {
				fmt.Fprintf(&b, "\nALTER TABLE %s ADD CONSTRAINT %s %s;", q(t.Name), q(r.ConstraintName), fk(r))
			}
		}
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// sqlString quotes s as a standard SQL string literal.
func sqlString(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }
