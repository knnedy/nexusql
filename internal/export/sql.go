package export

import (
	"fmt"
	"strings"

	"github.com/knnedy/nexusql/internal/db"
)

// SQL renders m as a DDL script for its own dialect: enum types, tables with
// keys, unique sets and checks, indexes, then foreign keys.
func SQL(m *Model) string {
	w := sqlWriter{m: m, d: m.Dialect.SQL()}
	var b strings.Builder
	b.WriteString("-- Generated by NexusQL from the introspected schema.\n")
	for _, e := range m.Enums {
		if w.d.EnumTypes {
			b.WriteString("\n" + w.enum(e) + "\n")
		}
	}
	for _, t := range m.Tables {
		b.WriteString("\n" + w.create(t) + "\n")
	}
	for _, t := range m.Tables {
		for _, s := range w.indexes(t) {
			b.WriteString("\n" + s)
		}
	}
	for _, t := range m.Tables {
		for _, s := range w.foreignKeys(t) {
			b.WriteString("\n" + s)
		}
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// TableSQL renders one table's CREATE TABLE, indexes and foreign keys.
func TableSQL(m *Model, name string) (string, bool) {
	w := sqlWriter{m: m, d: m.Dialect.SQL()}
	for _, t := range m.Tables {
		if t.Name == name {
			return strings.Join(append([]string{w.create(t)}, append(w.indexes(t), w.foreignKeys(t)...)...), "\n") + "\n", true
		}
	}
	return "", false
}

type sqlWriter struct {
	m *Model
	d db.SQLDialect
}

func (w sqlWriter) q(name string) string {
	s := string(w.d.Quote)
	return s + strings.ReplaceAll(name, s, s+s) + s
}

func (w sqlWriter) cols(fs []*Field) string {
	names := make([]string, len(fs))
	for i, f := range fs {
		names[i] = w.q(f.Name)
	}
	return strings.Join(names, ", ")
}

func (w sqlWriter) enum(e *Enum) string {
	vals := make([]string, len(e.Values))
	for i, v := range e.Values {
		vals[i] = sqlString(v.Name)
	}
	return fmt.Sprintf("CREATE TYPE %s AS ENUM (%s);", w.q(e.Name), strings.Join(vals, ", "))
}

func (w sqlWriter) create(t *Table) string {
	var lines []string
	for _, f := range t.Fields {
		typ, keepDefault := w.m.Dialect.SQLColumnType(f.Field)
		col := strings.TrimSpace(w.q(f.Name) + " " + typ)
		if !f.Nullable && !(f.IsPrimaryKey && (w.d.PKNotNull || f.AutoGenerated)) {
			col += " NOT NULL"
		}
		if keepDefault && f.DefaultValue != nil {
			col += " DEFAULT " + *f.DefaultValue
		}
		if len(t.PK) == 1 && t.PK[0] == f {
			col += " PRIMARY KEY"
			if f.Monotonic {
				col += " AUTOINCREMENT"
			}
		}
		lines = append(lines, col)
	}
	if len(t.PK) > 1 {
		lines = append(lines, "PRIMARY KEY ("+w.cols(t.PK)+")")
	}
	for _, u := range t.DeclaredUnique {
		lines = append(lines, "UNIQUE ("+w.cols(u)+")")
	}
	for _, c := range t.Checks {
		check := "CHECK (" + c.Expr + ")"
		if c.Name != "" {
			check = "CONSTRAINT " + w.q(c.Name) + " " + check
		}
		lines = append(lines, check)
	}
	if w.d.InlineForeignKeys {
		for _, r := range t.Out {
			lines = append(lines, w.fk(r))
		}
	}
	return fmt.Sprintf("CREATE TABLE %s (\n  %s\n);", w.q(t.Name), strings.Join(lines, ",\n  "))
}

func (w sqlWriter) indexes(t *Table) []string {
	var out []string
	for _, ix := range t.Indexes {
		out = append(out, fmt.Sprintf("CREATE INDEX %s ON %s (%s);", w.q(ix.Name), w.q(t.Name), w.cols(ix.Fields)))
	}
	return out
}

// foreignKeys are the ALTER TABLE statements adding t's foreign keys, where
// the dialect does not declare them inline.
func (w sqlWriter) foreignKeys(t *Table) []string {
	if w.d.InlineForeignKeys {
		return nil
	}
	var out []string
	for _, r := range t.Out {
		out = append(out, fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s %s;", w.q(t.Name), w.q(r.ConstraintName), w.fk(r)))
	}
	return out
}

func (w sqlWriter) fk(r *Relation) string {
	s := fmt.Sprintf("FOREIGN KEY (%s) REFERENCES %s (%s)", w.cols(r.FromFields), w.q(r.To.Name), w.cols(r.ToFields))
	if r.OnDelete != "" && r.OnDelete != db.NoAction {
		s += " ON DELETE " + string(r.OnDelete)
	}
	if r.OnUpdate != "" && r.OnUpdate != db.NoAction {
		s += " ON UPDATE " + string(r.OnUpdate)
	}
	return s
}

// sqlString quotes s as a standard SQL string literal.
func sqlString(s string) string { return "'" + strings.ReplaceAll(s, "'", "''") + "'" }
