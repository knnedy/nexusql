package postgres

import (
	"context"
	"fmt"

	"github.com/knnedy/nexusql/internal/db"
)

// Key flags come from pg_constraint by table oid: information_schema joins
// by constraint name alone mix up same-named constraints on different tables.
const queryTables = `
SELECT
    c.table_schema,
    c.table_name,
    c.column_name,
    c.udt_name,
    c.is_nullable,
    c.column_default,
    EXISTS (
        SELECT 1 FROM pg_constraint con
        WHERE con.conrelid = a.attrelid AND con.contype = 'p' AND a.attnum = ANY (con.conkey)
    ) AS is_primary_key,
    EXISTS (
        SELECT 1 FROM pg_constraint con
        WHERE con.conrelid = a.attrelid AND con.contype = 'f' AND a.attnum = ANY (con.conkey)
    ) AS is_foreign_key,
    (c.is_identity = 'YES' OR COALESCE(c.column_default LIKE 'nextval(%', false)) AS auto_generated,
    format_type(a.atttypid, a.atttypmod) AS native_type
FROM information_schema.columns c
JOIN pg_attribute a
    ON a.attrelid = format('%I.%I', c.table_schema, c.table_name)::regclass
    AND a.attname = c.column_name
WHERE c.table_schema = $1
ORDER BY c.table_name, c.ordinal_position
`

// One row per foreign key; conkey/confkey are unnested together so column
// pairs stay aligned instead of forming a cross product.
const queryRelations = `
SELECT
    con.conname,
    src.relname,
    tgt.relname,
    array_agg(sa.attname::text ORDER BY k.ord),
    array_agg(ta.attname::text ORDER BY k.ord)
FROM pg_constraint con
JOIN pg_class src ON src.oid = con.conrelid
JOIN pg_namespace n ON n.oid = src.relnamespace
JOIN pg_class tgt ON tgt.oid = con.confrelid
CROSS JOIN LATERAL unnest(con.conkey, con.confkey) WITH ORDINALITY AS k(src_att, tgt_att, ord)
JOIN pg_attribute sa ON sa.attrelid = con.conrelid AND sa.attnum = k.src_att
JOIN pg_attribute ta ON ta.attrelid = con.confrelid AND ta.attnum = k.tgt_att
WHERE con.contype = 'f' AND n.nspname = $1
GROUP BY con.oid, con.conname, src.relname, tgt.relname
ORDER BY con.conname, src.relname
`

const queryEnums = `
SELECT
    t.typname      AS enum_name,
    e.enumlabel    AS enum_value
FROM pg_type t
JOIN pg_enum e ON t.oid = e.enumtypid
JOIN pg_catalog.pg_namespace n ON n.oid = t.typnamespace
WHERE n.nspname = $1
ORDER BY t.typname, e.enumsortorder
`

func (p *provider) IntrospectSchema(ctx context.Context, schema string) (*db.Schema, error) {
	if schema == "" {
		schema = "public"
	}

	tables, err := p.introspectTables(ctx, schema)
	if err != nil {
		return nil, fmt.Errorf("introspect tables: %w", err)
	}

	if err := p.introspectUnique(ctx, schema, tables); err != nil {
		return nil, fmt.Errorf("introspect unique indexes: %w", err)
	}

	relations, err := p.introspectRelations(ctx, schema)
	if err != nil {
		return nil, fmt.Errorf("introspect relations: %w", err)
	}

	enums, err := p.introspectEnums(ctx, schema)
	if err != nil {
		return nil, fmt.Errorf("introspect enums: %w", err)
	}

	return &db.Schema{
		Tables:    tables,
		Relations: relations,
		Enums:     enums,
	}, nil
}

func (p *provider) introspectTables(ctx context.Context, schema string) ([]db.Table, error) {
	rows, err := p.pool.Query(ctx, queryTables, schema)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	tableMap := make(map[string]*db.Table)
	tableOrder := []string{}

	for rows.Next() {
		var (
			tableSchema   string
			tableName     string
			columnName    string
			udtName       string
			isNullable    string
			columnDef     *string
			isPrimaryKey  bool
			isForeignKey  bool
			autoGenerated bool
			nativeType    string
		)

		if err := rows.Scan(
			&tableSchema,
			&tableName,
			&columnName,
			&udtName,
			&isNullable,
			&columnDef,
			&isPrimaryKey,
			&isForeignKey,
			&autoGenerated,
			&nativeType,
		); err != nil {
			return nil, fmt.Errorf("scan row: %w", err)
		}

		if _, exists := tableMap[tableName]; !exists {
			tableMap[tableName] = &db.Table{
				Name:   tableName,
				Schema: tableSchema,
				Fields: make([]db.Field, 0),
			}
			tableOrder = append(tableOrder, tableName)
		}

		tableMap[tableName].Fields = append(tableMap[tableName].Fields, db.Field{
			Name:          columnName,
			Type:          normalizeType(udtName),
			Nullable:      isNullable == "YES",
			IsPrimaryKey:  isPrimaryKey,
			IsForeignKey:  isForeignKey,
			AutoGenerated: autoGenerated,
			DefaultValue:  columnDef,
			NativeType:    nativeType,
		})
	}

	if err := rows.Err(); err != nil {
		return nil, err
	}

	tables := make([]db.Table, 0, len(tableOrder))
	for _, name := range tableOrder {
		tables = append(tables, *tableMap[name])
	}

	return tables, nil
}

func (p *provider) introspectRelations(ctx context.Context, schema string) ([]db.Relation, error) {
	rows, err := p.pool.Query(ctx, queryRelations, schema)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	relations := make([]db.Relation, 0)

	for rows.Next() {
		var r db.Relation
		if err := rows.Scan(&r.ConstraintName, &r.SourceTable, &r.TargetTable, &r.SourceFields, &r.TargetFields); err != nil {
			return nil, fmt.Errorf("scan relation: %w", err)
		}
		r.SourceField, r.TargetField = r.SourceFields[0], r.TargetFields[0]
		relations = append(relations, r)
	}

	if err := rows.Err(); err != nil {
		return nil, err
	}

	return relations, nil
}

func (p *provider) introspectEnums(ctx context.Context, schema string) ([]db.EnumType, error) {
	rows, err := p.pool.Query(ctx, queryEnums, schema)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	enumMap := make(map[string]*db.EnumType)
	enumOrder := []string{}

	for rows.Next() {
		var name, value string
		if err := rows.Scan(&name, &value); err != nil {
			return nil, fmt.Errorf("scan enum: %w", err)
		}
		if _, exists := enumMap[name]; !exists {
			enumMap[name] = &db.EnumType{Name: name, Values: []string{}}
			enumOrder = append(enumOrder, name)
		}
		enumMap[name].Values = append(enumMap[name].Values, value)
	}

	if err := rows.Err(); err != nil {
		return nil, err
	}

	enums := make([]db.EnumType, 0, len(enumOrder))
	for _, name := range enumOrder {
		enums = append(enums, *enumMap[name])
	}

	return enums, nil
}

func (p *provider) DefaultSchema() string {
	return "public"
}
