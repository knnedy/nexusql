package postgres

import (
	"regexp"
	"strings"

	"github.com/knnedy/nexusql/internal/db"
)

// exporter gives the shared exporters Postgres's types and defaults.
type exporter struct{}

func (exporter) Drizzle() db.DrizzleDialect {
	return db.DrizzleDialect{
		Module: "drizzle-orm/pg-core", Table: "pgTable", AnyColumn: "AnyPgColumn",
		Enum: "pgEnum", NamedEnums: true, DefaultNow: true, BigInt: true,
	}
}

func (exporter) DrizzleColumn(f db.Field, name string) (string, []string) {
	_, args := db.TypeArgs(f.NativeType)
	call := func(builder string, opts ...string) (string, []string) {
		if len(opts) == 0 {
			return builder + "(" + name + ")", []string{builder}
		}
		return builder + "(" + name + ", { " + strings.Join(opts, ", ") + " })", []string{builder}
	}
	length := func() []string {
		if len(args) == 1 {
			return []string{"length: " + args[0]}
		}
		return nil
	}
	precision := func(opts ...string) []string {
		if len(args) == 1 {
			opts = append(opts, "precision: "+args[0])
		}
		return opts
	}
	if f.AutoGenerated {
		serial := f.DefaultValue != nil && strings.HasPrefix(*f.DefaultValue, "nextval(")
		switch {
		case serial && f.Type == db.FieldTypeSmallint:
			return call("smallserial")
		case serial && (f.Type == db.FieldTypeBigint || f.Type == db.FieldTypeBigserial):
			return call("bigserial", "mode: 'bigint'")
		case serial:
			return call("serial")
		}
		identity := ".generatedByDefaultAsIdentity()"
		if f.Identity == db.IdentityAlways {
			identity = ".generatedAlwaysAsIdentity()"
		}
		switch f.Type {
		case db.FieldTypeSmallint:
			c, i := call("smallint")
			return c + identity, i
		case db.FieldTypeBigint, db.FieldTypeBigserial:
			c, i := call("bigint", "mode: 'bigint'")
			return c + identity, i
		default:
			c, i := call("integer")
			return c + identity, i
		}
	}
	switch f.Type {
	case db.FieldTypeSmallint:
		return call("smallint")
	case db.FieldTypeInteger, db.FieldTypeSerial:
		return call("integer")
	case db.FieldTypeBigint, db.FieldTypeBigserial:
		return call("bigint", "mode: 'bigint'")
	case db.FieldTypeNumeric:
		if len(args) == 2 {
			return call("numeric", "precision: "+args[0], "scale: "+args[1])
		}
		return call("numeric")
	case db.FieldTypeReal:
		return call("real")
	case db.FieldTypeDoublePrecision:
		return call("doublePrecision")
	case db.FieldTypeVarchar:
		return call("varchar", length()...)
	case db.FieldTypeChar:
		return call("char", length()...)
	case db.FieldTypeText:
		return call("text")
	case db.FieldTypeBoolean:
		return call("boolean")
	case db.FieldTypeUUID:
		return call("uuid")
	case db.FieldTypeDate:
		return call("date")
	case db.FieldTypeTime:
		return call("time", precision()...)
	case db.FieldTypeTimestamp:
		return call("timestamp", precision()...)
	case db.FieldTypeTimestamptz:
		return call("timestamp", precision("withTimezone: true")...)
	case db.FieldTypeInterval:
		return call("interval")
	case db.FieldTypeJSON:
		return call("json")
	case db.FieldTypeJSONB:
		return call("jsonb")
	}
	return "", nil
}

func (exporter) PrismaProvider() string { return "postgresql" }

func (exporter) PrismaType(f db.Field) (string, string) {
	_, args := db.TypeArgs(f.NativeType)
	withArgs := func(attr string) string {
		if len(args) == 0 {
			return attr
		}
		return attr + "(" + strings.Join(args, ", ") + ")"
	}
	switch f.Type {
	case db.FieldTypeSmallint:
		return "Int", "@db.SmallInt"
	case db.FieldTypeInteger, db.FieldTypeSerial:
		return "Int", ""
	case db.FieldTypeBigint, db.FieldTypeBigserial:
		return "BigInt", ""
	case db.FieldTypeNumeric:
		return "Decimal", withArgs("@db.Decimal")
	case db.FieldTypeReal:
		return "Float", "@db.Real"
	case db.FieldTypeDoublePrecision:
		return "Float", ""
	case db.FieldTypeVarchar:
		return "String", withArgs("@db.VarChar")
	case db.FieldTypeChar:
		return "String", withArgs("@db.Char")
	case db.FieldTypeText:
		return "String", ""
	case db.FieldTypeBoolean:
		return "Boolean", ""
	case db.FieldTypeUUID:
		return "String", "@db.Uuid"
	case db.FieldTypeDate:
		return "DateTime", "@db.Date"
	case db.FieldTypeTime:
		return "DateTime", withPrecision("@db.Time", args)
	case db.FieldTypeTimestamp:
		return "DateTime", withPrecision("@db.Timestamp", args)
	case db.FieldTypeTimestamptz:
		return "DateTime", withPrecision("@db.Timestamptz", args)
	case db.FieldTypeJSON:
		return "Json", "@db.Json"
	case db.FieldTypeJSONB:
		return "Json", ""
	case db.FieldTypeBytea:
		return "Bytes", ""
	}
	return "", ""
}

// withPrecision states the precision Postgres uses when none is declared (6).
func withPrecision(attr string, args []string) string {
	if len(args) == 0 {
		return attr + "(6)"
	}
	return attr + "(" + args[0] + ")"
}

var trailingCast = regexp.MustCompile(`::[a-zA-Z_][\w ."]*(\(\d+(,\s*\d+)?\))?(\[\])?$`)

func (exporter) Default(f db.Field) db.Default {
	if f.DefaultValue == nil {
		return db.Default{}
	}
	e := strings.TrimSpace(*f.DefaultValue)
	for {
		stripped := strings.TrimSpace(trailingCast.ReplaceAllString(e, ""))
		if stripped == e {
			break
		}
		e = stripped
	}
	if strings.HasPrefix(e, "(") && strings.HasSuffix(e, ")") && db.ParseDefault(e[1:len(e)-1]).Kind == db.DefaultNumber {
		e = e[1 : len(e)-1] // negative numbers come back as (-1)
	}
	return db.ParseDefault(e)
}

func (exporter) SQL() db.SQLDialect {
	return db.SQLDialect{Quote: '"', EnumTypes: true, PKNotNull: true}
}

func (exporter) SQLColumnType(f db.Field) (string, bool) {
	if !f.AutoGenerated {
		return f.NativeType, true
	}
	if f.Identity != "" {
		return f.NativeType + " GENERATED " + string(f.Identity) + " AS IDENTITY", false
	}
	switch f.NativeType { // a nextval default: serial creates the same sequence
	case "smallint":
		return "smallserial", false
	case "bigint":
		return "bigserial", false
	}
	return "serial", false
}
