package db

type FieldType string

const (
	FieldTypeSerial          FieldType = "serial"
	FieldTypeBigserial       FieldType = "bigserial"
	FieldTypeSmallint        FieldType = "smallint"
	FieldTypeInteger         FieldType = "integer"
	FieldTypeBigint          FieldType = "bigint"
	FieldTypeNumeric         FieldType = "numeric"
	FieldTypeReal            FieldType = "real"
	FieldTypeDoublePrecision FieldType = "double precision"
	FieldTypeChar            FieldType = "char"
	FieldTypeVarchar         FieldType = "varchar"
	FieldTypeText            FieldType = "text"
	FieldTypeBoolean         FieldType = "boolean"
	FieldTypeUUID            FieldType = "uuid"
	FieldTypeDate            FieldType = "date"
	FieldTypeTime            FieldType = "time"
	FieldTypeTimestamp       FieldType = "timestamp"
	FieldTypeTimestamptz     FieldType = "timestamptz"
	FieldTypeInterval        FieldType = "interval"
	FieldTypeJSON            FieldType = "json"
	FieldTypeJSONB           FieldType = "jsonb"
	FieldTypeBytea           FieldType = "bytea"
)

type SortDir string

const (
	SortAsc  SortDir = "asc"
	SortDesc SortDir = "desc"
)

type Field struct {
	Name         string    `json:"name"`
	Type         FieldType `json:"type"`
	Nullable     bool      `json:"nullable"`
	IsPrimaryKey bool      `json:"isPrimaryKey"`
	IsForeignKey bool      `json:"isForeignKey"`
	DefaultValue *string   `json:"defaultValue"` // a SQL expression in the dialect
	// AutoGenerated: the database assigns the value when it is omitted
	// (rowid alias, AUTO_INCREMENT, serial, identity).
	AutoGenerated bool `json:"autoGenerated"`
	// NativeType is the type as the database declares it, e.g. varchar(40).
	NativeType string `json:"nativeType"`
	// Allowed lists the only values a CHECK (column IN (...)) constraint accepts.
	Allowed []string `json:"allowed,omitempty"`
}

type Table struct {
	Name   string  `json:"name"`
	Schema string  `json:"schema"`
	Fields []Field `json:"fields"`
}

type Relation struct {
	ConstraintName string `json:"constraintName"`
	SourceTable    string `json:"sourceTable"`
	SourceField    string `json:"sourceField"`
	TargetTable    string `json:"targetTable"`
	TargetField    string `json:"targetField"`
	// SourceFields and TargetFields are every column pair, in key order;
	// SourceField and TargetField repeat the first pair.
	SourceFields []string `json:"sourceFields"`
	TargetFields []string `json:"targetFields"`
}

// IsComposite reports whether the foreign key spans several columns.
func (r Relation) IsComposite() bool { return len(r.SourceFields) > 1 }

type EnumType struct {
	Name   string   `json:"name"`
	Values []string `json:"values"`
}

type Schema struct {
	Tables    []Table    `json:"tables"`
	Relations []Relation `json:"relations"`
	Enums     []EnumType `json:"enums"`
}

// Table returns the introspected table with this exact name.
func (s *Schema) Table(name string) (Table, bool) {
	for _, t := range s.Tables {
		if t.Name == name {
			return t, true
		}
	}
	return Table{}, false
}

// Field returns the column with this exact name.
func (t Table) Field(name string) (Field, bool) {
	for _, f := range t.Fields {
		if f.Name == name {
			return f, true
		}
	}
	return Field{}, false
}
