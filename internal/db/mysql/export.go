package mysql

import (
	"slices"
	"strings"

	"github.com/knnedy/nexusql/internal/db"
)

// exporter gives the shared exporters MySQL's types and defaults.
type exporter struct{}

func (exporter) Drizzle() db.DrizzleDialect {
	return db.DrizzleDialect{
		Module: "drizzle-orm/mysql-core", Table: "mysqlTable", AnyColumn: "AnyMySqlColumn",
		Enum: "mysqlEnum", BigInt: true,
	}
}

func (exporter) DrizzleColumn(f db.Field, name string) (string, []string) {
	base, args := db.TypeArgs(f.NativeType)
	unsigned := strings.HasSuffix(base, " unsigned")
	base = strings.TrimSuffix(base, " unsigned")
	call := func(builder string, opts ...string) (string, []string) {
		if unsigned {
			opts = append(opts, "unsigned: true")
		}
		c := builder + "(" + name + ")"
		if len(opts) > 0 {
			c = builder + "(" + name + ", { " + strings.Join(opts, ", ") + " })"
		}
		if f.AutoGenerated {
			c += ".autoincrement()"
		}
		return c, []string{builder}
	}
	fsp := func() []string {
		if len(args) == 1 {
			return []string{"fsp: " + args[0]}
		}
		return nil
	}
	if f.Type == db.FieldTypeBoolean {
		return call("boolean")
	}
	switch base {
	case "tinyint", "smallint", "mediumint", "int":
		return call(base)
	case "integer":
		return call("int")
	case "bigint":
		return call("bigint", "mode: 'bigint'")
	case "decimal", "numeric":
		if len(args) == 2 {
			return call("decimal", "precision: "+args[0], "scale: "+args[1])
		}
		return call("decimal")
	case "float":
		return call("float")
	case "double", "real":
		return call("double")
	case "varchar", "varbinary":
		if len(args) != 1 {
			return "", nil // drizzle requires the length
		}
		return call(base, "length: "+args[0])
	case "char", "binary":
		if len(args) == 1 {
			return call(base, "length: "+args[0])
		}
		return call(base)
	case "text", "tinytext", "mediumtext", "longtext", "date", "json", "year":
		return call(base)
	case "time", "datetime", "timestamp":
		return call(base, fsp()...)
	}
	return "", nil
}

func (exporter) PrismaProvider() string { return "mysql" }

var mysqlInts = map[string]string{
	"tinyint": "TinyInt", "smallint": "SmallInt", "mediumint": "MediumInt", "int": "", "integer": "",
}

var mysqlNative = map[string]string{
	"text": "@db.Text", "tinytext": "@db.TinyText", "mediumtext": "@db.MediumText", "longtext": "@db.LongText",
	"blob": "@db.Blob", "tinyblob": "@db.TinyBlob", "mediumblob": "@db.MediumBlob", "longblob": "@db.LongBlob",
	"date": "@db.Date",
}

func (exporter) PrismaType(f db.Field) (string, string) {
	name, args := db.TypeArgs(f.NativeType)
	unsigned := strings.HasSuffix(name, " unsigned")
	name = strings.TrimSuffix(name, " unsigned")
	withArgs := func(attr string) string {
		if len(args) == 0 {
			return attr
		}
		return attr + "(" + strings.Join(args, ", ") + ")"
	}
	if f.Type == db.FieldTypeBoolean {
		return "Boolean", ""
	}
	switch name {
	case "tinyint", "smallint", "mediumint", "int", "integer":
		attr := mysqlInts[name]
		if unsigned {
			attr = "Unsigned" + attr
			if attr == "Unsigned" {
				attr = "UnsignedInt"
			}
		}
		if attr == "" {
			return "Int", ""
		}
		return "Int", "@db." + attr
	case "bigint":
		if unsigned {
			return "BigInt", "@db.UnsignedBigInt"
		}
		return "BigInt", ""
	case "decimal", "numeric":
		return "Decimal", withArgs("@db.Decimal")
	case "float":
		return "Float", "@db.Float"
	case "double", "real":
		return "Float", ""
	case "varchar":
		return "String", withArgs("@db.VarChar")
	case "char":
		return "String", withArgs("@db.Char")
	case "binary":
		return "Bytes", withArgs("@db.Binary")
	case "varbinary":
		return "Bytes", withArgs("@db.VarBinary")
	case "time":
		return "DateTime", "@db.Time(" + precision(args) + ")"
	case "datetime":
		return "DateTime", "@db.DateTime(" + precision(args) + ")"
	case "timestamp":
		return "DateTime", "@db.Timestamp(" + precision(args) + ")"
	case "json":
		return "Json", ""
	}
	if attr, ok := mysqlNative[name]; ok {
		if strings.HasSuffix(attr, "Blob") {
			return "Bytes", attr
		}
		if attr == "@db.Date" {
			return "DateTime", attr
		}
		return "String", attr
	}
	return "", ""
}

// precision is the declared fractional-second precision; MySQL's default is 0.
func precision(args []string) string {
	if len(args) == 0 {
		return "0"
	}
	return args[0]
}

func (exporter) Default(f db.Field) db.Default {
	if f.DefaultValue == nil {
		return db.Default{}
	}
	return db.ParseDefault(*f.DefaultValue)
}

func (exporter) SQL() db.SQLDialect { return db.SQLDialect{Quote: '`', PKNotNull: true} }

func (exporter) SQLColumnType(f db.Field) (string, bool) {
	if f.AutoGenerated {
		return f.NativeType + " AUTO_INCREMENT", false
	}
	return f.NativeType, true
}

// KyselyType follows mysql2: decimal arrives as a string, bigint as a number
// (without supportBigNumbers), dates as Date, tinyint(1) as a number.
func (exporter) KyselyType(f db.Field) string {
	switch f.Type {
	case db.FieldTypeSmallint, db.FieldTypeInteger, db.FieldTypeSerial, db.FieldTypeBigint,
		db.FieldTypeBigserial, db.FieldTypeReal, db.FieldTypeDoublePrecision, db.FieldTypeBoolean:
		return "number"
	case db.FieldTypeNumeric:
		return "Numeric"
	case db.FieldTypeText, db.FieldTypeVarchar, db.FieldTypeChar, db.FieldTypeUUID, db.FieldTypeTime:
		return "string"
	case db.FieldTypeDate, db.FieldTypeTimestamp, db.FieldTypeTimestamptz:
		return "Timestamp"
	case db.FieldTypeJSON, db.FieldTypeJSONB:
		return "Json"
	case db.FieldTypeBytea:
		return "Buffer"
	}
	return ""
}

// TypeORMType: TypeORM turns on mysql2's bigNumberStrings, so bigint and
// decimal are strings; tinyint(1) stays a number, dates are strings.
// TypeORM maps tinyint(1) to boolean, which hydrates booleans (it creates a
// plain tinyint: TypeORM 1 has no display widths).
func (exporter) TypeORM(f db.Field) db.TypeORMColumn {
	if base, args := db.TypeArgs(f.NativeType); base == "tinyint" && len(args) == 1 && args[0] == "1" {
		return db.TypeORMColumn{TS: "boolean", Type: "boolean"}
	}
	return db.TypeORMColumn{TS: typeormTS(f)}
}

func typeormTS(f db.Field) string {
	switch f.Type {
	case db.FieldTypeSmallint, db.FieldTypeInteger, db.FieldTypeSerial, db.FieldTypeReal,
		db.FieldTypeDoublePrecision, db.FieldTypeBoolean:
		return "number"
	case db.FieldTypeBigint, db.FieldTypeBigserial, db.FieldTypeNumeric, db.FieldTypeDate,
		db.FieldTypeText, db.FieldTypeVarchar, db.FieldTypeChar, db.FieldTypeUUID, db.FieldTypeTime:
		return "string"
	case db.FieldTypeTimestamp, db.FieldTypeTimestamptz:
		return "Date"
	case db.FieldTypeBytea:
		return "Buffer"
	}
	return ""
}

// GORM: parentheses would make an expression default (DEFAULT_GENERATED), so
// literals go as values GORM quotes; GORM trims quotes at either end first.
func (e exporter) GORM(f db.Field) db.GORMColumn {
	if f.DefaultValue == nil || f.AutoGenerated {
		return db.GORMColumn{}
	}
	d := e.Default(f)
	switch d.Kind {
	case db.DefaultNone:
		return db.GORMColumn{}
	case db.DefaultNumber, db.DefaultBool:
		return db.GORMColumn{Default: d.Value}
	case db.DefaultNow:
		return db.GORMColumn{Default: *f.DefaultValue} // (CURRENT_TIMESTAMP) would be now()
	case db.DefaultString:
		if d.Value != "" && !strings.ContainsAny(d.Value[:1]+d.Value[len(d.Value)-1:], `'"`) {
			return db.GORMColumn{Default: d.Value}
		}
	}
	return db.GORMParenDefault(f)
}

// SQLAlchemy: SQLAlchemy wraps a default with a non-word character in
// parentheses (an expression default), so numbers such as 1.50 go quoted.
func (e exporter) SQLAlchemy(f db.Field) db.SQLAlchemyColumn {
	c := db.SQLAlchemyColumn{Type: sqlalchemyType(f)}
	if f.DefaultValue != nil && !f.AutoGenerated {
		if d := e.Default(f); d.Kind == db.DefaultNumber && strings.ContainsAny(d.Value, ".-+eE") {
			c.Literal = d.Value
		}
	}
	return c
}

// sqlalchemyType names the SQLAlchemy type that renders f's type as MySQL
// reports it; tinyint(1) is BOOLEAN, which MySQL stores as tinyint(1).
func sqlalchemyType(f db.Field) string {
	base, args := db.TypeArgs(f.NativeType)
	unsigned := strings.HasSuffix(base, " unsigned")
	base = strings.TrimSuffix(base, " unsigned")
	arg := func(i int) string { return args[i] }
	switch {
	case base == "tinyint" && len(args) == 1 && args[0] == "1" && !unsigned:
		return "BOOLEAN()"
	case slices.Contains([]string{"tinyint", "smallint", "mediumint", "int", "bigint"}, base) && len(args) == 0:
		name := map[string]string{"tinyint": "TINYINT", "smallint": "SMALLINT", "mediumint": "MEDIUMINT", "int": "INTEGER", "bigint": "BIGINT"}[base]
		if unsigned {
			return "mysql." + name + "(unsigned=True)"
		}
		return "mysql." + name + "()"
	case unsigned:
		return ""
	case base == "decimal" && len(args) == 2:
		return "DECIMAL(" + arg(0) + ", " + arg(1) + ")"
	case (base == "varchar" || base == "char") && len(args) == 1:
		return strings.ToUpper(base) + "(" + arg(0) + ")"
	case slices.Contains([]string{"text", "date", "json", "blob"}, base) && len(args) == 0:
		return strings.ToUpper(base) + "()"
	case base == "float" && len(args) == 0:
		return "mysql.FLOAT()"
	case base == "double" && len(args) == 0:
		return "mysql.DOUBLE()"
	case slices.Contains([]string{"datetime", "timestamp", "time"}, base):
		if len(args) == 1 {
			return "mysql." + strings.ToUpper(base) + "(fsp=" + arg(0) + ")"
		}
		return "mysql." + strings.ToUpper(base) + "()"
	}
	return ""
}
