package mysql

import (
	"strings"

	"github.com/knnedy/nexusql/internal/db"
)

// exporter gives the shared exporters MySQL's types and defaults.
type exporter struct{}

func (exporter) Drizzle() db.DrizzleDialect {
	return db.DrizzleDialect{
		Module: "drizzle-orm/mysql-core", Table: "mysqlTable", AnyColumn: "AnyMySqlColumn",
		Enum: "mysqlEnum", BigInt: true,
	}
}

func (exporter) DrizzleColumn(f db.Field, name string) (string, []string) {
	base, args := db.TypeArgs(f.NativeType)
	unsigned := strings.HasSuffix(base, " unsigned")
	base = strings.TrimSuffix(base, " unsigned")
	call := func(builder string, opts ...string) (string, []string) {
		if unsigned {
			opts = append(opts, "unsigned: true")
		}
		c := builder + "(" + name + ")"
		if len(opts) > 0 {
			c = builder + "(" + name + ", { " + strings.Join(opts, ", ") + " })"
		}
		if f.AutoGenerated {
			c += ".autoincrement()"
		}
		return c, []string{builder}
	}
	fsp := func() []string {
		if len(args) == 1 {
			return []string{"fsp: " + args[0]}
		}
		return nil
	}
	if f.Type == db.FieldTypeBoolean {
		return call("boolean")
	}
	switch base {
	case "tinyint", "smallint", "mediumint", "int":
		return call(base)
	case "integer":
		return call("int")
	case "bigint":
		return call("bigint", "mode: 'bigint'")
	case "decimal", "numeric":
		if len(args) == 2 {
			return call("decimal", "precision: "+args[0], "scale: "+args[1])
		}
		return call("decimal")
	case "float":
		return call("float")
	case "double", "real":
		return call("double")
	case "varchar", "varbinary":
		if len(args) != 1 {
			return "", nil // drizzle requires the length
		}
		return call(base, "length: "+args[0])
	case "char", "binary":
		if len(args) == 1 {
			return call(base, "length: "+args[0])
		}
		return call(base)
	case "text", "tinytext", "mediumtext", "longtext", "date", "json", "year":
		return call(base)
	case "time", "datetime", "timestamp":
		return call(base, fsp()...)
	}
	return "", nil
}

func (exporter) PrismaProvider() string { return "mysql" }

var mysqlInts = map[string]string{
	"tinyint": "TinyInt", "smallint": "SmallInt", "mediumint": "MediumInt", "int": "", "integer": "",
}

var mysqlNative = map[string]string{
	"text": "@db.Text", "tinytext": "@db.TinyText", "mediumtext": "@db.MediumText", "longtext": "@db.LongText",
	"blob": "@db.Blob", "tinyblob": "@db.TinyBlob", "mediumblob": "@db.MediumBlob", "longblob": "@db.LongBlob",
	"date": "@db.Date",
}

func (exporter) PrismaType(f db.Field) (string, string) {
	name, args := db.TypeArgs(f.NativeType)
	unsigned := strings.HasSuffix(name, " unsigned")
	name = strings.TrimSuffix(name, " unsigned")
	withArgs := func(attr string) string {
		if len(args) == 0 {
			return attr
		}
		return attr + "(" + strings.Join(args, ", ") + ")"
	}
	if f.Type == db.FieldTypeBoolean {
		return "Boolean", ""
	}
	switch name {
	case "tinyint", "smallint", "mediumint", "int", "integer":
		attr := mysqlInts[name]
		if unsigned {
			attr = "Unsigned" + attr
			if attr == "Unsigned" {
				attr = "UnsignedInt"
			}
		}
		if attr == "" {
			return "Int", ""
		}
		return "Int", "@db." + attr
	case "bigint":
		if unsigned {
			return "BigInt", "@db.UnsignedBigInt"
		}
		return "BigInt", ""
	case "decimal", "numeric":
		return "Decimal", withArgs("@db.Decimal")
	case "float":
		return "Float", "@db.Float"
	case "double", "real":
		return "Float", ""
	case "varchar":
		return "String", withArgs("@db.VarChar")
	case "char":
		return "String", withArgs("@db.Char")
	case "binary":
		return "Bytes", withArgs("@db.Binary")
	case "varbinary":
		return "Bytes", withArgs("@db.VarBinary")
	case "time":
		return "DateTime", "@db.Time(" + precision(args) + ")"
	case "datetime":
		return "DateTime", "@db.DateTime(" + precision(args) + ")"
	case "timestamp":
		return "DateTime", "@db.Timestamp(" + precision(args) + ")"
	case "json":
		return "Json", ""
	}
	if attr, ok := mysqlNative[name]; ok {
		if strings.HasSuffix(attr, "Blob") {
			return "Bytes", attr
		}
		if attr == "@db.Date" {
			return "DateTime", attr
		}
		return "String", attr
	}
	return "", ""
}

// precision is the declared fractional-second precision; MySQL's default is 0.
func precision(args []string) string {
	if len(args) == 0 {
		return "0"
	}
	return args[0]
}

func (exporter) Default(f db.Field) db.Default {
	if f.DefaultValue == nil {
		return db.Default{}
	}
	return db.ParseDefault(*f.DefaultValue)
}
