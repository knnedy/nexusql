const queryTableNames = `
SELECT name FROM sqlite_master
WHERE type = 'table' AND name NOT LIKE 'sqlite_%'
ORDER BY name
`

func (p *provider) IntrospectSchema(ctx context.Context, schema string) (*db.Schema, error) {
	tableNames, err := p.introspectTableNames(ctx)
	if err != nil {
		return nil, fmt.Errorf("introspect table names: %w", err)
	}

	tables := make([]db.Table, 0, len(tableNames))
	relations := make([]db.Relation, 0)

	for _, name := range tableNames {
		fkRows, err := p.foreignKeyRows(ctx, name)
		if err != nil {
			return nil, fmt.Errorf("introspect foreign keys for %s: %w", name, err)
		}

		fields, err := p.introspectColumns(ctx, name, fkRows)
		if err != nil {
			return nil, fmt.Errorf("introspect columns for %s: %w", name, err)
		}
		unique, err := p.uniqueSets(ctx, name)
		if err != nil {
			return nil, fmt.Errorf("introspect unique indexes for %s: %w", name, err)
		}
		tables = append(tables, db.Table{Name: name, Schema: "", Fields: fields, Unique: unique})

		rels, err := buildRelations(ctx, p, name, fkRows)
		if err != nil {
			return nil, fmt.Errorf("build relations for %s: %w", name, err)
		}
		relations = append(relations, rels...)
	}

	return &db.Schema{
		Tables:    tables,
		Relations: relations,
		Enums:     []db.EnumType{}, // SQLite has no native enum type
	}, nil
}

func (p *provider) introspectTableNames(ctx context.Context) ([]string, error) {
	rows, err := p.conn.QueryContext(ctx, queryTableNames)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	var names []string
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			return nil, fmt.Errorf("scan table name: %w", err)
		}
		names = append(names, name)
	}
	return names, rows.Err()
}

// fkRow mirrors one row of PRAGMA foreign_key_list output. Multiple rows
// share the same id when a foreign key spans multiple columns; seq gives
// each row's position within that composite key.
type fkRow struct {
	id, seq     int
	targetTable string
	sourceField string
	targetField string
}

// foreignKeyRows runs PRAGMA foreign_key_list once per table; the result is
// reused for both column-level IsForeignKey flags and relation building, so
// the pragma is never queried twice for the same table.
func (p *provider) foreignKeyRows(ctx context.Context, tableName string) ([]fkRow, error) {
	query := fmt.Sprintf("PRAGMA foreign_key_list(%s)", quoteIdent(tableName))
	rows, err := p.conn.QueryContext(ctx, query)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	var out []fkRow
	for rows.Next() {
		var (
			id, seq                       int
			table, from                   string
			to, onUpdate, onDelete, match sql.NullString
		)
		if err := rows.Scan(&id, &seq, &table, &from, &to, &onUpdate, &onDelete, &match); err != nil {
			return nil, fmt.Errorf("scan foreign key: %w", err)
		}
		out = append(out, fkRow{
			id:          id,
			seq:         seq,
			targetTable: table,
			sourceField: from,
			targetField: to.String,
		})
	}
	return out, rows.Err()
}

func (p *provider) introspectColumns(ctx context.Context, tableName string, fkRows []fkRow) ([]db.Field, error) {
	cols, err := p.tableInfo(ctx, tableName)
	if err != nil {
		return nil, err
	}
	fkCols := map[string]bool{}
	for _, fk := range fkRows {
		fkCols[fk.sourceField] = true
	}

	var createSQL sql.NullString
	if err := p.conn.QueryRowContext(ctx,
		"SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ?", tableName).Scan(&createSQL); err != nil {
		return nil, fmt.Errorf("read table definition: %w", err)
	}
	allowed := allowedValues(createSQL.String)

	pkCount := 0
	for _, c := range cols {
		if c.pk > 0 {
			pkCount++
		}
	}

	fields := make([]db.Field, 0, len(cols))
	for _, c := range cols {
		// Only a lone column declared exactly INTEGER PRIMARY KEY aliases the
		// rowid: never NULL, assigned on insert when omitted.
		rowid := c.pk > 0 && pkCount == 1 && strings.EqualFold(strings.TrimSpace(c.declType), "INTEGER")
		var defaultValue *string
		if c.dflt.Valid {
			v := defaultExpr(c.dflt.String)
			defaultValue = &v
		}
		fields = append(fields, db.Field{
			Name:          c.name,
			Type:          normalizeType(c.declType),
			Nullable:      c.notNull == 0 && !rowid,
			IsPrimaryKey:  c.pk > 0,
			IsForeignKey:  fkCols[c.name],
			DefaultValue:  defaultValue,
			AutoGenerated: rowid,
			Allowed:       allowed[strings.ToLower(c.name)],
			NativeType:    c.declType,
		})
	}
	return fields, nil
}

// column is one row of PRAGMA table_info.
type column struct {
	name, declType string
	notNull, pk    int // pk is the 1-based position in the primary key, 0 if none
	dflt           sql.NullString
}

func (p *provider) tableInfo(ctx context.Context, tableName string) ([]column, error) {
	rows, err := p.conn.QueryContext(ctx, fmt.Sprintf("PRAGMA table_info(%s)", quoteIdent(tableName)))
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	var cols []column
	for rows.Next() {
		var c column
		var cid int
		if err := rows.Scan(&cid, &c.name, &c.declType, &c.notNull, &c.dflt, &c.pk); err != nil {
			return nil, fmt.Errorf("scan column: %w", err)
		}
		cols = append(cols, c)
	}
	return cols, rows.Err()
}

// buildRelations groups PRAGMA foreign_key_list rows by id into one relation
// per foreign key, columns in key order.
func buildRelations(ctx context.Context, p *provider, tableName string, fkRows []fkRow) ([]db.Relation, error) {
	byID := map[int][]fkRow{}
	var order []int
	for _, r := range fkRows {
		if _, exists := byID[r.id]; !exists {
			order = append(order, r.id)
		}
		byID[r.id] = append(byID[r.id], r)
	}
	sort.Ints(order)

	var relations []db.Relation
	for _, id := range order {
		group := byID[id]
		sort.Slice(group, func(i, j int) bool { return group[i].seq < group[j].seq })

		var src, dst []string
		for _, r := range group {
			src = append(src, r.sourceField)
			dst = append(dst, r.targetField)
		}
		if dst[0] == "" {
			// REFERENCES parent without columns targets parent's primary key.
			pk, err := p.primaryKeyColumns(ctx, group[0].targetTable)
			if err != nil {
				return nil, fmt.Errorf("resolve implicit FK target for %s: %w", group[0].targetTable, err)
			}
			if len(pk) != len(src) {
				return nil, fmt.Errorf("foreign key on %s has %d columns but %s has a %d-column primary key",
					tableName, len(src), group[0].targetTable, len(pk))
			}
			dst = pk
		}

		relations = append(relations, db.Relation{
			ConstraintName: fmt.Sprintf("fk_%s_%d", tableName, id),
			SourceTable:    tableName,
			SourceField:    src[0],
			TargetTable:    group[0].targetTable,
			TargetField:    dst[0],
			SourceFields:   src,
			TargetFields:   dst,
		})
	}
	return relations, nil
}

// primaryKeyColumns lists tableName's primary-key columns in key order.
func (p *provider) primaryKeyColumns(ctx context.Context, tableName string) ([]string, error) {
	cols, err := p.tableInfo(ctx, tableName)
	if err != nil {
		return nil, err
	}
	sort.Slice(cols, func(i, j int) bool { return cols[i].pk < cols[j].pk })
	var out []string
	for _, c := range cols {
		if c.pk > 0 {
			out = append(out, c.name)
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("%s has no primary key", tableName)
	}
	return out, nil
}

func quoteIdent(name string) string {
	return `"` + strings.ReplaceAll(name, `"`, `""`) + `"`
}

// DefaultSchema returns "" — SQLite's IntrospectSchema ignores its schema
// parameter entirely (see queryTableNames), so there's no literal to
// return here.
func (p *provider) DefaultSchema() string {
	return ""
}

var sqliteLiteral = regexp.MustCompile(`(?i)^([-+]?(\d+\.?\d*|\.\d+)(e[-+]?\d+)?|0x[0-9a-f]+|'(''|[^'])*'|x'[0-9a-f]*'|null|true|false|current_(timestamp|date|time))$`)

// defaultExpr restores the parentheses PRAGMA table_info drops from expression
// defaults, which CREATE TABLE requires; literals are left as they are.
func defaultExpr(v string) string {
	if sqliteLiteral.MatchString(strings.TrimSpace(v)) {
		return v
	}
	return "(" + v + ")"
}
