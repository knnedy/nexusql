import type { RefAction, Relation, Table } from "@/shared/types/schema";

/** What a column's "Keys and rules" cell says about it. */
export type Rule =
  | { kind: "generated" }
  | { kind: "references"; table: string; column: string; onDelete: RefAction }
  | { kind: "oneOf"; values: string[] }
  | { kind: "check"; expr: string }
  | { kind: "unique" }
  | { kind: "indexed" };

const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const mentions = (expr: string, column: string) => new RegExp(`(^|[^\\w"])"?${escape(column)}"?([^\\w"]|$)`, "i").test(expr);

/** Per column: generated, the key it points along, allowed values, its own checks, uniqueness, index. */
export function columnRules(table: Table, relations: Relation[]): Record<string, Rule[]> {
  const out: Record<string, Rule[]> = {};
  for (const f of table.fields) {
    const rules: Rule[] = [];
    if (f.autoGenerated || f.identity) rules.push({ kind: "generated" });
    for (const r of relations) {
      const at = r.sourceTable === table.name ? r.sourceFields.indexOf(f.name) : -1;
      if (at >= 0) rules.push({ kind: "references", table: r.targetTable, column: r.targetFields[at], onDelete: r.onDelete });
    }
    if (f.allowed?.length) rules.push({ kind: "oneOf", values: f.allowed });
    for (const c of table.checks ?? []) {
      // A check belongs to a column only when it names no other; allowed values already show its IN list.
      const own = mentions(c.expr, f.name) && table.fields.every((o) => o.name === f.name || !mentions(c.expr, o.name));
      if (own && !(f.allowed?.length && /\bIN\s*\(/i.test(c.expr))) rules.push({ kind: "check", expr: c.expr });
    }
    if (table.unique?.some((u) => u.length === 1 && u[0] === f.name)) rules.push({ kind: "unique" });
    else if (!f.isPrimaryKey && table.indexes?.some((i) => i.columns[0] === f.name)) rules.push({ kind: "indexed" });
    out[f.name] = rules;
  }
  return out;
}

/** What deleting does along a key, in words; cascades warn because they remove rows. */
export function deleteEffect(action: RefAction, direction: "out" | "in", other: string): { text: string; warn: boolean } {
  if (action !== "CASCADE") return { text: `on delete ${action.toLowerCase()}`, warn: false };
  return direction === "out"
    ? { text: `deleted with its ${other} row`, warn: true }
    : { text: `its ${other} rows are deleted with it`, warn: true };
}

export interface TableSummary {
  name: string;
  columns: number;
  pointsTo: number;
  pointedToBy: number;
}

/** Every table at a glance, A to Z; a key to its own table counts neither way. */
export function tableOverview(tables: Table[], relations: Relation[]): TableSummary[] {
  const links = relations.filter((r) => r.sourceTable !== r.targetTable);
  return tables
    .map((t) => ({
      name: t.name,
      columns: t.fields.length,
      pointsTo: links.filter((r) => r.sourceTable === t.name).length,
      pointedToBy: links.filter((r) => r.targetTable === t.name).length,
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}
