import { describe, expect, it } from "vitest";
import type { Field, Relation, Table } from "@/shared/types/schema";
import { columnRules, deleteEffect, tableOverview } from "./structure";

const field = (name: string, over: Partial<Field> = {}): Field => ({
  name, type: "integer", nativeType: "integer", nullable: true, isPrimaryKey: false, isForeignKey: false,
  defaultValue: null, autoGenerated: false, ...over,
});
const rel = (source: string, cols: string[], target: string, targetCols: string[], onDelete: Relation["onDelete"] = "NO ACTION"): Relation => ({
  constraintName: `${source}_${cols.join("_")}_fk`, sourceTable: source, sourceField: cols[0], targetTable: target, targetField: targetCols[0],
  sourceFields: cols, targetFields: targetCols, onDelete, onUpdate: "NO ACTION",
});

const orders: Table = {
  name: "orders", schema: "main",
  fields: [
    field("id", { isPrimaryKey: true, nullable: false, autoGenerated: true }),
    field("customer_id", { isForeignKey: true, nullable: false }),
    field("status", { type: "varchar", allowed: ["pending", "paid"] }),
    field("total_cents"),
    field("placed_at"),
    field("code", { type: "text" }),
  ],
  unique: [["code"], ["customer_id", "placed_at"]],
  indexes: [{ name: "orders_placed_idx", columns: ["placed_at"] }],
  checks: [
    { name: "", expr: "status IN ('pending', 'paid')" },
    { name: "positive", expr: "total_cents >= 0" },
    { name: "", expr: "placed_at IS NOT NULL OR status = 'pending'" },
  ],
};
const relations = [rel("orders", ["customer_id"], "customers", ["id"], "CASCADE"), rel("items", ["order_id"], "orders", ["id"])];

describe("columnRules", () => {
  const rules = columnRules(orders, relations);

  it("says the database fills a generated key", () => {
    expect(rules.id).toEqual([{ kind: "generated" }]);
  });

  it("names the column a foreign key points to and what deleting it does", () => {
    expect(rules.customer_id).toEqual([{ kind: "references", table: "customers", column: "id", onDelete: "CASCADE" }]);
  });

  it("lists allowed values once, not again as their CHECK", () => {
    expect(rules.status).toEqual([{ kind: "oneOf", values: ["pending", "paid"] }]);
  });

  it("puts a check on the one column it constrains, not on columns it only mentions alongside others", () => {
    expect(rules.total_cents).toEqual([{ kind: "check", expr: "total_cents >= 0" }]);
    expect(rules.placed_at).toEqual([{ kind: "indexed" }]);
  });

  it("marks a column unique on its own, but not for a key it shares", () => {
    expect(rules.code).toEqual([{ kind: "unique" }]);
  });
});

describe("deleteEffect", () => {
  it("spells out cascades in plain words, either way round", () => {
    expect(deleteEffect("CASCADE", "out", "customers")).toEqual({ text: "deleted with its customers row", warn: true });
    expect(deleteEffect("CASCADE", "in", "items")).toEqual({ text: "its items rows are deleted with it", warn: true });
    expect(deleteEffect("SET NULL", "in", "items")).toEqual({ text: "on delete set null", warn: false });
  });
});

describe("tableOverview", () => {
  it("counts columns and keys each way per table, A to Z, ignoring keys to itself", () => {
    const items: Table = { name: "items", schema: "main", fields: [field("id"), field("order_id"), field("parent_id")] };
    const customers: Table = { name: "customers", schema: "main", fields: [field("id")] };
    const all = [...relations, rel("items", ["parent_id"], "items", ["id"])];
    expect(tableOverview([orders, items, customers], all)).toEqual([
      { name: "customers", columns: 1, pointsTo: 0, pointedToBy: 1 },
      { name: "items", columns: 3, pointsTo: 1, pointedToBy: 0 },
      { name: "orders", columns: 6, pointsTo: 1, pointedToBy: 1 },
    ]);
  });
});
