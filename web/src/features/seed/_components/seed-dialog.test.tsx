import { QueryClient } from "@tanstack/react-query";
import { render, screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, expect, it, vi } from "vitest";
import { api } from "@/shared/api/client";
import { queryKeys } from "@/shared/api/query-keys";
import { readOnlyQueryOptions } from "@/shared/hooks/use-read-only";
import type { SchemaResponse } from "@/shared/types/schema";
import { withClient } from "@/test/connection-cache";
import { ToastProvider } from "@/shared/ui/toast";
import { SeedDialog } from "./seed-dialog";

const field = (name: string, type: string, extra = {}) => ({ name, type, nativeType: type, nullable: false, isPrimaryKey: false, isForeignKey: false, ...extra });
const SCHEMA = {
  tables: [
    { name: "customers", schema: "", fields: [field("id", "integer", { isPrimaryKey: true, autoGenerated: true }), field("email", "text")] },
    { name: "addresses", schema: "", fields: [field("id", "integer", { isPrimaryKey: true, autoGenerated: true }), field("customer_id", "integer", { isForeignKey: true })] },
    {
      name: "orders",
      schema: "",
      fields: [
        field("id", "integer", { isPrimaryKey: true, autoGenerated: true }),
        field("customer_id", "integer", { isForeignKey: true }),
        field("note", "text", { nullable: true }),
        field("total_cents", "integer"),
      ],
    },
  ],
  relations: [
    { sourceTable: "addresses", targetTable: "customers" },
    { sourceTable: "orders", targetTable: "customers" },
  ],
  enums: [],
} as unknown as SchemaResponse;

afterEach(() => vi.restoreAllMocks());

function open({ readOnly = false, table = "orders", onOpenData = vi.fn() } = {}) {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
  client.setQueryData(queryKeys.seedPlan(), { order: ["customers", "addresses", "orders"] });
  client.setQueryData(readOnlyQueryOptions().queryKey, { readOnly });
  vi.spyOn(api, "seedSample").mockResolvedValue({
    rows: [{ note: null, total_cents: "18450" }, { note: "leave at door", total_cents: "399" }, { note: "gift", total_cents: "72100" }],
    refs: { customer_id: "customers" },
    auto: ["id"],
  });
  const Wrapper = withClient(client);
  render(
    <Wrapper>
      <ToastProvider>
        <SeedDialog open onClose={() => {}} schema={SCHEMA} table={table} onOpenData={onOpenData} />
      </ToastProvider>
    </Wrapper>,
  );
  return { onOpenData };
}

const plan = () => screen.getByRole("list", { name: "Tables, in the order rows go in" });
const row = (name: string) => within(plan()).getByRole("listitem", { name });

it("lists the tables in the order rows go in, with what each needs", () => {
  open();
  expect(within(plan()).getAllByRole("listitem").map((li) => li.getAttribute("aria-label"))).toEqual(["customers", "addresses", "orders"]);
  expect(row("orders")).toHaveTextContent("needs customers");
  expect(row("customers")).toHaveTextContent("no keys to other tables");
  expect(screen.getByText(/Adds 30 rows to 3 tables/)).toBeInTheDocument();
});

it("points keys at existing rows when a parent is left out", async () => {
  open();
  await userEvent.click(within(row("customers")).getByRole("checkbox", { name: "Seed customers" }));
  expect(row("orders")).toHaveTextContent("existing customers rows");
  expect(screen.getByRole("button", { name: "Add 20 rows" })).toBeEnabled();
});

it("sets every table's count at once, or one table's own", async () => {
  open();
  const every = screen.getByRole("spinbutton", { name: "Rows for every table" });
  await userEvent.clear(every);
  await userEvent.type(every, "5");
  expect(within(row("orders")).getByRole("spinbutton")).toHaveValue(5);
  const orders = within(row("orders")).getByRole("spinbutton", { name: "Rows for orders" });
  await userEvent.clear(orders);
  await userEvent.type(orders, "40");
  expect(screen.getByRole("button", { name: "Add 50 rows" })).toBeInTheDocument();
});

it("shows sample rows of the chosen table before anything is written", async () => {
  open();
  const sample = await screen.findByRole("table", { name: "Sample rows of orders" });
  expect(sample).toHaveTextContent("→ customers");
  expect(sample).toHaveTextContent("auto");
  expect(sample).toHaveTextContent("empty");
  expect(sample).toHaveTextContent("18450");
  await userEvent.click(within(row("customers")).getByRole("button", { name: /^customers/ }));
  expect(api.seedSample).toHaveBeenLastCalledWith({ table: "customers", rows: 3, nullChance: 0.2 });
});

it("seeds the plan, then reports what went in and why rows were skipped", async () => {
  const seed = vi.spyOn(api, "seed").mockResolvedValue({
    rowsInserted: { customers: 10, addresses: 10, orders: 8 },
    skipped: { orders: 2 },
    problems: { orders: "CHECK constraint failed: total_cents >= 0" },
  });
  const { onOpenData } = open();
  await userEvent.click(screen.getByRole("button", { name: "Add 30 rows" }));
  expect(seed.mock.calls[0][0]).toEqual({ rowsPerTable: 1, nullChance: 0.2, tables: { customers: 10, addresses: 10, orders: 10 } });
  expect(await screen.findByText(/Added 28 rows to 3 tables/)).toBeInTheDocument();
  expect(row("orders")).toHaveTextContent("8 · 2 skipped");
  expect(screen.getByText(/CHECK constraint failed/)).toBeInTheDocument();
  await userEvent.click(screen.getByRole("button", { name: "Open orders" }));
  expect(onOpenData).toHaveBeenCalledWith("orders");
});

it("explains why it cannot seed a read-only connection", () => {
  open({ readOnly: true });
  expect(screen.getByText(/read-only/)).toBeInTheDocument();
  expect(screen.getByRole("button", { name: "Add 30 rows" })).toBeDisabled();
});
