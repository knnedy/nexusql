import { render, screen } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { describe, expect, it, vi } from "vitest";
import type { Field } from "@/shared/types/schema";
import { editKey } from "../lib/row-key";
import DataGrid, { type PendingEdit } from "./data-grid";

function field(name: string, type: string, extra: Partial<Field> = {}): Field {
  return {
    name,
    type: type as Field["type"],
    nullable: true,
    isPrimaryKey: false,
    isForeignKey: false,
    defaultValue: null,
    autoGenerated: false,
    ...extra,
  };
}

const fields = [
  field("id", "integer", { isPrimaryKey: true, nullable: false }),
  field("name", "text", { nullable: false }),
  field("nick", "text"),
  field("meta", "json"),
  field("active", "boolean"),
  field("mood", "mood"),
];
const rows = [
  { id: 1, name: "Rex", nick: null, meta: { a: 1 }, active: true, mood: "happy" },
  { id: 2, name: "Tom", nick: "", meta: null, active: false, mood: "sad" },
];

function renderGrid(
  props: {
    pendingEdits?: Map<string, PendingEdit>;
    readOnlyReason?: string | null;
    fields?: Field[];
  } = {},
) {
  const cols = props.fields ?? fields;
  const onCellEdit = vi.fn();
  render(
    <DataGrid
      tableName="pets"
      columns={cols.map((f) => f.name)}
      fields={cols}
      enums={[{ name: "mood", values: ["happy", "sad"] }]}
      relations={[]}
      rows={rows}
      isLoading={false}
      isError={false}
      sortCol=""
      sortDir="asc"
      onSort={() => {}}
      pendingEdits={props.pendingEdits ?? new Map()}
      onCellEdit={onCellEdit}
      onNavigateFk={() => {}}
      columnVisibility={{}}
      onColumnVisibilityChange={() => {}}
      readOnlyReason={props.readOnlyReason ?? null}
    />,
  );
  return { onCellEdit, user: userEvent.setup() };
}

describe("DataGrid editing", () => {
  it("sets NULL on a nullable column", async () => {
    const { onCellEdit, user } = renderGrid();
    await user.dblClick(screen.getByText("Tom"));
    expect(screen.queryByRole("button", { name: "Set NULL" })).toBeNull(); // name is NOT NULL
    await user.keyboard("{Escape}");

    await user.dblClick(screen.getAllByText("null")[0]); // Rex's nick
    await user.click(screen.getByRole("button", { name: "Set NULL" }));
    expect(onCellEdit).not.toHaveBeenCalled(); // already NULL: nothing to save

    await user.dblClick(screen.getByText("empty")); // Tom's nick is ""
    await user.click(screen.getByRole("button", { name: "Set NULL" }));
    expect(onCellEdit).toHaveBeenCalledOnce();
    expect(onCellEdit).toHaveBeenCalledWith(
      expect.objectContaining({ key: { id: "2" }, column: "nick", newValue: null }),
    );
  });

  it("offers NULL in enum and boolean pickers", async () => {
    const { onCellEdit, user } = renderGrid();
    await user.dblClick(screen.getByText("happy"));
    await user.selectOptions(screen.getByRole("combobox"), "NULL");
    await user.dblClick(screen.getByText("false"));
    await user.selectOptions(screen.getByRole("combobox"), "true");
    expect(onCellEdit.mock.calls.map(([e]) => [e.column, e.newValue])).toEqual([
      ["mood", null],
      ["active", "true"],
    ]);
  });

  it("does not record an edit that changes nothing", async () => {
    const { onCellEdit, user } = renderGrid();
    await user.dblClick(screen.getByText('{"a":1}'));
    await user.keyboard("{Enter}");
    await user.dblClick(screen.getByText("Rex"));
    await user.keyboard("{Enter}");
    expect(onCellEdit).not.toHaveBeenCalled();
  });

  it("shows NULL and the empty string differently", () => {
    renderGrid();
    expect(screen.getAllByText("null").length).toBeGreaterThan(0);
    expect(screen.getByText("empty")).toBeInTheDocument();
  });

  it("shows why a save failed", () => {
    const edit: PendingEdit = {
      key: { id: "1" },
      column: "name",
      newValue: "Rexy",
      originalValue: "Rex",
      error: "CHECK constraint failed",
    };
    renderGrid({ pendingEdits: new Map([[editKey(edit.key, edit.column), edit]]) });
    expect(screen.getByText("Rexy")).toBeInTheDocument();
    expect(screen.getByLabelText("Save failed: CHECK constraint failed")).toBeInTheDocument();
  });

  it("explains a read-only grid and opens no editor", async () => {
    const { user } = renderGrid({ readOnlyReason: "This table has no primary key." });
    expect(screen.getByRole("status")).toHaveTextContent("no primary key");
    await user.dblClick(screen.getByText("Tom"));
    expect(screen.queryByRole("textbox")).toBeNull();
  });

  it("explains why a table without a primary key is read-only", async () => {
    const { user } = renderGrid({
      fields: fields.map((f) => ({ ...f, isPrimaryKey: false })),
    });
    expect(screen.getByRole("status")).toHaveTextContent("no primary key");
    await user.dblClick(screen.getByText("Tom"));
    expect(screen.queryByRole("textbox")).toBeNull();
  });
});
