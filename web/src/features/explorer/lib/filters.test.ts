import { describe, expect, it } from "vitest";
import type { EnumType, Field } from "@/shared/types/schema";
import {
  choicesFor,
  describeFilter,
  isComplete,
  kindOf,
  opsFor,
  parseFilters,
  serializeFilters,
  type RowFilter,
} from "./filters";

function field(name: string, type: string, extra: Partial<Field> = {}): Field {
  return {
    name,
    type: type as Field["type"],
    nullable: true,
    isPrimaryKey: false,
    isForeignKey: false,
    defaultValue: null,
    nativeType: type,
    autoGenerated: false,
    ...extra,
  };
}

const enums: EnumType[] = [{ name: "mood", values: ["happy", "sad"] }];

describe("kindOf", () => {
  it.each([
    ["varchar", "text"],
    ["uuid", "text"],
    ["bigint", "number"],
    ["double precision", "number"],
    ["timestamptz", "temporal"],
    ["date", "temporal"],
    ["boolean", "boolean"],
    ["jsonb", "json"],
    ["bytea", "other"],
    ["mood", "choice"],
  ])("%s is %s", (type, kind) => {
    expect(kindOf(field("c", type), enums)).toBe(kind);
  });

  it("a CHECK IN list makes any column a choice", () => {
    expect(kindOf(field("size", "text", { allowed: ["s", "m"] }), enums)).toBe("choice");
  });
});

describe("opsFor", () => {
  it("matches what the server accepts for each kind", () => {
    expect(opsFor("text")).toEqual(["eq", "ne", "contains", "startsWith", "isNull", "notNull"]);
    expect(opsFor("number")).toEqual(["eq", "ne", "lt", "lte", "gt", "gte", "isNull", "notNull"]);
    expect(opsFor("temporal")).toEqual(opsFor("number"));
    expect(opsFor("boolean")).toEqual(["eq", "ne", "in", "isNull", "notNull"]);
    expect(opsFor("choice")).toEqual(opsFor("boolean"));
    expect(opsFor("json")).toEqual(["isNull", "notNull"]);
    expect(opsFor("other")).toEqual(["eq", "ne", "isNull", "notNull"]);
  });
});

describe("choicesFor", () => {
  it("lists enum, CHECK and boolean values; nothing for free text", () => {
    expect(choicesFor(field("m", "mood"), enums)).toEqual(["happy", "sad"]);
    expect(choicesFor(field("s", "text", { allowed: ["s", "m"] }), enums)).toEqual(["s", "m"]);
    expect(choicesFor(field("b", "boolean"), enums)).toEqual(["true", "false"]);
    expect(choicesFor(field("t", "text"), enums)).toBeNull();
  });
});

describe("describeFilter", () => {
  it.each<[RowFilter, string]>([
    [{ column: "age", op: "gte", values: ["18"] }, "age ≥ 18"],
    [{ column: "age", op: "ne", values: ["3"] }, "age ≠ 3"],
    [{ column: "name", op: "contains", values: ["ab"] }, 'name contains "ab"'],
    [{ column: "name", op: "startsWith", values: ["A"] }, 'name starts with "A"'],
    [{ column: "mood", op: "in", values: ["happy", "sad"] }, "mood is one of happy, sad"],
    [{ column: "nick", op: "isNull", values: [] }, "nick is null"],
    [{ column: "nick", op: "notNull", values: [] }, "nick is not null"],
  ])("%j reads %s", (f, text) => {
    expect(describeFilter(f)).toBe(text);
  });
});

describe("isComplete", () => {
  it("needs a value unless the operator takes none", () => {
    expect(isComplete({ column: "a", op: "eq", values: [""] })).toBe(false);
    expect(isComplete({ column: "a", op: "eq", values: ["0"] })).toBe(true);
    expect(isComplete({ column: "a", op: "in", values: [] })).toBe(false);
    expect(isComplete({ column: "a", op: "isNull", values: [] })).toBe(true);
  });
});

describe("parseFilters", () => {
  it("round-trips through the URL value", () => {
    const fs: RowFilter[] = [
      { column: "age", op: "gte", values: ["18"] },
      { column: "nick", op: "isNull", values: [] },
    ];
    expect(parseFilters(serializeFilters(fs))).toEqual(fs);
  });

  it("drops what it cannot read instead of failing", () => {
    expect(parseFilters("not json")).toEqual([]);
    expect(parseFilters('{"column":"a"}')).toEqual([]);
    expect(
      parseFilters('[{"column":"a","op":"eq","values":["1"]},{"column":1},{"column":"b","op":"zz","values":[]}]'),
    ).toEqual([{ column: "a", op: "eq", values: ["1"] }]);
  });

  it("serializes no filters as an empty value", () => {
    expect(serializeFilters([])).toBe("");
  });
});
