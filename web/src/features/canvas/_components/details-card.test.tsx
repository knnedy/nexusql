import { QueryClient } from "@tanstack/react-query";
import { render, screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { expect, it, vi } from "vitest";
import { withClient } from "@/test/connection-cache";
import type { Field, Relation, Table } from "@/shared/types/schema";
import { TooltipProvider } from "@/shared/ui/tooltip";
import { DetailsCard } from "./details-card";

vi.mock("next-themes", () => ({ useTheme: () => ({ resolvedTheme: "dark" }) }));

const field = (name: string, extra: Partial<Field> = {}): Field => ({
  name, type: "integer", nullable: true, isPrimaryKey: false, isForeignKey: false,
  defaultValue: null, nativeType: "INTEGER", autoGenerated: false, ...extra,
});
const ORDERS: Table = {
  name: "orders", schema: "main",
  fields: [field("id", { isPrimaryKey: true, nullable: false }), field("customer_id", { isForeignKey: true })],
  checks: [{ name: "status_ok", expr: "status IN ('paid', 'shipped')" }],
};
const rel = (source: string, field: string, target: string, onDelete: Relation["onDelete"] = "NO ACTION"): Relation => ({
  constraintName: `${source}_${field}_fkey`, sourceTable: source, sourceField: field, sourceFields: [field],
  targetTable: target, targetField: "id", targetFields: ["id"], onDelete, onUpdate: "NO ACTION",
});
const RELATIONS = [rel("orders", "customer_id", "customers", "CASCADE"), rel("payments", "order_id", "orders")];

function renderCard(props: Partial<Parameters<typeof DetailsCard>[0]> = {}) {
  const handlers = { onSelectTable: vi.fn(), onOpenData: vi.fn(), onClose: vi.fn() };
  const Wrapper = withClient(new QueryClient());
  render(
    <Wrapper>
      <TooltipProvider>
        <DetailsCard table={ORDERS} relation={null} tables={[ORDERS]} relations={RELATIONS} {...handlers} {...props} />
      </TooltipProvider>
    </Wrapper>,
  );
  return handlers;
}

it("lists what the table points to and what points to it, and picking one selects it", async () => {
  const { onSelectTable } = renderCard();
  const card = screen.getByRole("complementary", { name: "Details" });
  expect(within(card).getByRole("group", { name: "Points to" })).toHaveTextContent(/customers\s*customer_id/);
  expect(within(card).getByRole("group", { name: "Pointed to by" })).toHaveTextContent(/payments\s*order_id/);
  await userEvent.click(within(card).getByRole("button", { name: /payments/ }));
  expect(onSelectTable).toHaveBeenCalledWith("payments");
});

it("shows the table's keys and checks as the database has them", () => {
  renderCard();
  expect(screen.getByText("(customer_id) → customers (id) · ON DELETE CASCADE")).toBeInTheDocument();
  expect(screen.getByText("status_ok")).toBeInTheDocument();
});

it("opens the table's data", async () => {
  const { onOpenData } = renderCard();
  await userEvent.click(screen.getByRole("button", { name: "Open data" }));
  expect(onOpenData).toHaveBeenCalledWith("orders");
});

it("for a relationship, names both ends and their columns, and either end opens", async () => {
  const { onSelectTable } = renderCard({ table: null, relation: RELATIONS[1] });
  const card = screen.getByRole("complementary", { name: "Details" });
  expect(card).toHaveTextContent("payments_order_id_fkey");
  expect(card).toHaveTextContent(/payments\s*\.order_id/);
  await userEvent.click(within(card).getByRole("button", { name: /^orders/ }));
  expect(onSelectTable).toHaveBeenCalledWith("orders");
});
