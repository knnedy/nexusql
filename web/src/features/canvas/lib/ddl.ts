import type { DatabaseProvider } from "@/shared/types/provider";
import type { Relation, Table } from "@/shared/types/schema";

/** Approximates a CREATE TABLE statement for the inspector from introspected schema. */
export function buildDdl(
  table: Table,
  provider: DatabaseProvider | null,
  relations: Relation[],
): string {
  const q = provider === "mysql" ? "`" : '"';
  const id = (name: string) => `${q}${name}${q}`;
  const list = (names: string[]) => names.map(id).join(", ");
  const schemaPrefix =
    table.schema && table.schema !== "public" ? `${id(table.schema)}.` : "";

  const pk = table.fields.filter((f) => f.isPrimaryKey).map((f) => f.name);
  const inlinePk = pk.length === 1;

  const lines = table.fields.map((f) => {
    const parts: string[] = [`  ${id(f.name)}`, f.type.toUpperCase()];
    if (f.isPrimaryKey && inlinePk) parts.push("PRIMARY KEY");
    if (!f.nullable && !(f.isPrimaryKey && inlinePk)) parts.push("NOT NULL");
    if (f.autoGenerated && provider === "mysql") parts.push("AUTO_INCREMENT");
    if (f.autoGenerated && provider === "postgres" && !f.defaultValue) {
      parts.push("GENERATED BY DEFAULT AS IDENTITY");
    }
    if (f.defaultValue) parts.push(`DEFAULT ${f.defaultValue}`);
    return parts.join(" ");
  });

  if (!inlinePk && pk.length > 0) lines.push(`  PRIMARY KEY (${list(pk)})`);

  const own = relations.filter((r) => r.sourceTable === table.name);
  const covered = new Set(own.flatMap((r) => r.sourceFields));
  const fkLines = [
    ...own.map(
      (r) =>
        `  FOREIGN KEY (${list(r.sourceFields)}) REFERENCES ${id(r.targetTable)} (${list(r.targetFields)})`,
    ),
    ...table.fields
      .filter((f) => f.isForeignKey && !covered.has(f.name))
      .map((f) => `  FOREIGN KEY (${id(f.name)}) REFERENCES -- unknown`),
  ];

  return `CREATE TABLE ${schemaPrefix}${id(table.name)} (\n${[...lines, ...fkLines].join(",\n")}\n);`;
}
