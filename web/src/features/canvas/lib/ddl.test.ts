import { describe, expect, it } from "vitest";
import type { Field, Relation, Table } from "@/shared/types/schema";
import { buildDdl } from "./ddl";

const col = (name: string, over: Partial<Field> = {}): Field => ({
  name,
  type: "integer",
  nullable: false,
  isPrimaryKey: false,
  isForeignKey: false,
  defaultValue: null,
  autoGenerated: false,
  ...over,
});

const rel = (src: string[], target: string, dst: string[]): Relation => ({
  constraintName: "fk",
  sourceTable: "child",
  sourceField: src[0],
  targetTable: target,
  targetField: dst[0],
  sourceFields: src,
  targetFields: dst,
});

describe("buildDdl", () => {
  it("renders a single-column key table", () => {
    const users: Table = {
      name: "users",
      schema: "public",
      fields: [
        col("id", { isPrimaryKey: true }),
        col("email", { type: "text" }),
        col("note", { type: "text", nullable: true, defaultValue: "'x'" }),
      ],
    };

    expect(buildDdl(users, "postgres", [])).toBe(
      'CREATE TABLE "users" (\n  "id" INTEGER PRIMARY KEY,\n  "email" TEXT NOT NULL,\n  "note" TEXT DEFAULT \'x\'\n);',
    );
  });

  it("puts a composite primary key and foreign key on one line each", () => {
    const child: Table = {
      name: "child",
      schema: "",
      fields: [
        col("a", { isPrimaryKey: true }),
        col("b", { isPrimaryKey: true }),
        col("pa", { isForeignKey: true }),
        col("pb", { isForeignKey: true }),
      ],
    };

    expect(buildDdl(child, "sqlite", [rel(["pa", "pb"], "parent", ["x", "y"])])).toBe(
      'CREATE TABLE "child" (\n  "a" INTEGER NOT NULL,\n  "b" INTEGER NOT NULL,\n' +
        '  "pa" INTEGER NOT NULL,\n  "pb" INTEGER NOT NULL,\n  PRIMARY KEY ("a", "b"),\n' +
        '  FOREIGN KEY ("pa", "pb") REFERENCES "parent" ("x", "y")\n);',
    );
  });

  it("marks auto-generated keys in each dialect's words", () => {
    const t = (provider: "mysql" | "postgres" | "sqlite") =>
      buildDdl(
        { name: "t", schema: "", fields: [col("id", { isPrimaryKey: true, autoGenerated: true })] },
        provider,
        [],
      );

    expect(t("mysql")).toContain("`id` INTEGER PRIMARY KEY AUTO_INCREMENT");
    expect(t("postgres")).toContain('"id" INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY');
    expect(t("sqlite")).toContain('"id" INTEGER PRIMARY KEY\n');
  });

  it("keeps the serial default Postgres reports instead of an identity clause", () => {
    const ddl = buildDdl(
      {
        name: "t",
        schema: "",
        fields: [col("id", { isPrimaryKey: true, autoGenerated: true, defaultValue: "nextval('t_id_seq'::regclass)" })],
      },
      "postgres",
      [],
    );

    expect(ddl).toContain(`"id" INTEGER PRIMARY KEY DEFAULT nextval('t_id_seq'::regclass)`);
  });
});
