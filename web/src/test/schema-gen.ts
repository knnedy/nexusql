import type { Field, Relation, SchemaResponse, Table } from "@/shared/types/schema";

function field(name: string, pk = false, fk = false): Field {
  return {
    name,
    type: pk || fk ? "integer" : "text",
    nativeType: pk || fk ? "integer" : "text",
    nullable: !pk,
    isPrimaryKey: pk,
    isForeignKey: fk,
    defaultValue: null,
    autoGenerated: pk,
  };
}

/**
 * A deterministic schema shaped like large real ones: modules of 8-24 tables that
 * mostly reference each other, a few global hubs (users, orgs) most tables reference,
 * some cross-module keys, and every 25th table on its own.
 */
export function generateSchema(n: number, seed = 7): SchemaResponse {
  const rnd = () => (seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648;
  const pick = (from: number, to: number) => from + Math.floor(rnd() * (to - from));
  const HUBS = Math.min(3, n);
  const tables: Table[] = [];
  const relations: Relation[] = [];
  let moduleStart = HUBS;
  let moduleEnd = HUBS;
  for (let i = 0; i < n; i++) {
    if (i >= moduleEnd) {
      moduleStart = i;
      moduleEnd = i + pick(8, 25);
    }
    const name = `t${i}`;
    const fields = [field("id", true)];
    const width = 3 + Math.floor(rnd() * 8);
    for (let c = 0; c < width; c++) fields.push(field(`c${c}`));
    const targets = new Set<number>();
    if (i >= HUBS && i % 25 !== 0) {
      if (rnd() < 0.5) targets.add(pick(0, HUBS));
      if (i > moduleStart) targets.add(pick(moduleStart, i));
      if (i > moduleStart + 1 && rnd() < 0.4) targets.add(pick(moduleStart, i));
      if (moduleStart > HUBS && rnd() < 0.15) targets.add(pick(HUBS, moduleStart));
    } else if (i > 0 && i < HUBS) {
      targets.add(0);
    }
    for (const target of targets) {
      const col = `t${target}_id`;
      fields.push(field(col, false, true));
      relations.push({
        constraintName: `${name}_${col}_fkey`,
        sourceTable: name,
        sourceField: col,
        targetTable: `t${target}`,
        targetField: "id",
        sourceFields: [col],
        targetFields: ["id"],
        onDelete: "NO ACTION",
        onUpdate: "NO ACTION",
      });
    }
    tables.push({ name, schema: "main", fields });
  }
  return { tables, relations, enums: [] };
}
