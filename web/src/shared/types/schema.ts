export type FieldType =
  // Numeric
  | "serial"
  | "bigserial"
  | "smallint"
  | "integer"
  | "bigint"
  | "numeric"
  | "real"
  | "double precision"
  // Character
  | "char"
  | "varchar"
  | "text"
  // Boolean
  | "boolean"
  // UUID
  | "uuid"
  // Date / Time
  | "date"
  | "time"
  | "timestamp"
  | "timestamptz"
  | "interval"
  // JSON
  | "json"
  | "jsonb"
  // Binary
  | "bytea"
  // Fallback for any provider-specific type not listed above
  | (string & {});

