export interface Field {
  name: string;
  type: FieldType;
  nullable: boolean;
  isPrimaryKey: boolean;
  isForeignKey: boolean;
  /** The default as a SQL expression in the connection's dialect. */
  defaultValue: string | null;
  /** The type as the database declares it, e.g. varchar(40). */
  nativeType: string;
  /** The database assigns the value when omitted (rowid, AUTO_INCREMENT, serial, identity). */
  autoGenerated: boolean;
  /** The only values a single-column CHECK (column IN (...)) allows, on every dialect. */
  allowed?: string[];
  /** Set on GENERATED ... AS IDENTITY columns. */
  identity?: "ALWAYS" | "BY DEFAULT";
  /** Generated keys are never reused, even after deletes (SQLite AUTOINCREMENT). */
  monotonic?: boolean;
}

export interface Table {
  name: string;
  schema: string;
  fields: Field[];
  /** Unique constraints and full unique indexes other than the primary key. */
  unique?: string[][];
  /** Plain (non-unique) column indexes by name; partial and expression ones are left out. */
  indexes?: Index[];
  /** CHECK constraints as the database prints them; name is "" for unnamed SQLite ones. */
  checks?: Check[];
}

export interface Check {
  name: string;
  expr: string;
}

export interface Index {
  name: string;
  columns: string[];
}

export interface Relation {
  constraintName: string;
  sourceTable: string;
  sourceField: string;
  targetTable: string;
  targetField: string;
  /** Every column pair in key order; sourceField/targetField repeat the first. */
  sourceFields: string[];
  targetFields: string[];
  onDelete: RefAction;
  onUpdate: RefAction;
}

/** What a foreign key does when its referenced row is deleted or its key updated. */
export type RefAction = "NO ACTION" | "RESTRICT" | "CASCADE" | "SET NULL" | "SET DEFAULT";

export interface EnumType {
  name: string;
  values: string[];
}

export interface SchemaResponse {
  tables: Table[];
  relations: Relation[];
  enums: EnumType[];
}
