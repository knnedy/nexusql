import { expect, test } from "@playwright/test";
import { connectSqlite } from "./helpers";

const SHOP = `
CREATE TABLE customers (id INTEGER PRIMARY KEY AUTOINCREMENT, email TEXT NOT NULL UNIQUE);
CREATE TABLE orders (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  customer_id INTEGER NOT NULL REFERENCES customers (id) ON DELETE CASCADE,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid')),
  total_cents INTEGER NOT NULL DEFAULT 0 CHECK (total_cents >= 0),
  placed_at TEXT
);
CREATE INDEX orders_placed_idx ON orders (placed_at);
CREATE TABLE items (id INTEGER PRIMARY KEY, order_id INTEGER REFERENCES orders (id) ON DELETE CASCADE)`;

test("structure lists every table, then shows a table's columns, rules, keys and links", async ({ page }) => {
  await connectSqlite(page, SHOP);
  await page.getByRole("tab", { name: "Structure" }).click();
  await expect(page).toHaveURL(/view=structure/);

  const every = page.getByRole("table", { name: "Every table" });
  await expect(every.getByRole("rowheader")).toHaveText(["customers", "items", "orders"]);
  await every.getByRole("link", { name: "orders" }).click();
  await expect(page).toHaveURL(/table=orders/);
  await expect(page.getByRole("heading", { level: 2 })).toHaveText("orders");

  const row = (name: string) => page.getByRole("row").filter({ has: page.getByRole("rowheader", { name, exact: true }) });
  await expect(row("id")).toContainText("generated by the database");
  await expect(row("customer_id")).toContainText("customers.id");
  await expect(row("customer_id")).toContainText("deleted with its customers row");
  await expect(row("status")).toContainText("one of");
  await expect(row("status")).not.toContainText("check");
  await expect(row("total_cents")).toContainText("check total_cents >= 0");
  await expect(row("placed_at")).toContainText("indexed");

  await expect(page.getByRole("group", { name: "Pointed to by" })).toContainText("its items rows are deleted with it");
  await expect(page.getByRole("region", { name: "CREATE statement" })).toContainText("CREATE TABLE");

  await row("customer_id").getByRole("link", { name: "references customers.id" }).click();
  await expect(page).toHaveURL(/table=customers/);
  await expect(page.getByRole("heading", { level: 2 })).toHaveText("customers");
  await expect(row("email")).toContainText("unique");
});

test("copies one table in any export format", async ({ page, context }) => {
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  await connectSqlite(page, SHOP);
  await page.goto("/studio/?view=structure&table=orders");
  await page.getByRole("button", { name: "Copy as" }).click();
  await page.getByRole("menuitem", { name: /Prisma schema/ }).click();
  await expect(page.getByText("Copied orders as Prisma schema")).toBeVisible();
  const copied = await page.evaluate(() => navigator.clipboard.readText());
  expect(copied).toContain("model orders {");
  expect(copied).not.toContain("model customers {");
});
